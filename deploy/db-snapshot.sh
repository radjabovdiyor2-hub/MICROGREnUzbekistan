#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
# Снимок боевой базы перед необратимым шагом.
#
# ЗАЧЕМ
#
# Выкатка меняет СХЕМУ прода без участия человека: unify_databases.sql
# переименовывает таблицы, а db-push идёт с `--accept-data-loss`. Флаг не
# значит, что данные теряются каждый раз, — он значит, что Prisma не
# остановится и не спросит, когда правка окажется разрушительной.
#
# Мержей в main бывает по четыре за сутки, а единственная копия снималась
# раз в ночь (daily_backup, 03:00 — bots/stepan_bot). Значит цена неудачной
# правки схемы измерялась часами до ближайшего дампа и зависела от того,
# который час.
#
# Тот же снимок нужен перед `relink_pos_sales --apply`: он переписывает
# привязку чеков к клиентам и счётчики карточек.
#
# ПОВЕДЕНИЕ ПРИ ОТКАЗЕ
#
# Ненулевой код возврата. Вызывающий обязан остановиться: день без новой
# версии дешевле дня без пути назад.
#
# Запуск:  sh deploy/db-snapshot.sh <метка>
#          метка попадает в имя файла — это либо коротки́й sha выкатки,
#          либо имя ручной операции.
# ══════════════════════════════════════════════════════════════════════
set -e

LABEL="${1:-manual}"
SNAP_DIR="${SNAP_DIR:-/opt/microgreen/backups/predeploy}"
PG_CONTAINER="${PG_CONTAINER:-mg_postgres}"
PG_USER="${PG_USER:-mg_user}"
PG_DB="${PG_DB:-microgreen}"
# Сколько снимков держим. Хватает, чтобы отступить на несколько выкаток
# назад, и не хватает, чтобы забить диск.
KEEP="${KEEP:-5}"
# Запасной каталог — там, где пользователь выкатки хозяин заведомо.
FALLBACK_DIR="${FALLBACK_DIR:-$HOME/microgreen-backups/predeploy}"

# ── Каталог для снимков выбираем, а не назначаем ──────────────────────
#
# ПРОВЕРЕНО БОЕМ, а не рассуждением: первая же выкатка с этим скриптом
# встала на `mkdir: cannot create directory '/opt/microgreen/backups/
# predeploy': Permission denied`. Причина — `backups/` на сервере создаёт
# Docker под bind-mount девопс-бота, то есть от root, и пользователь
# выкатки внутрь писать не может.
#
# Встала БЕЗОПАСНО: до unify_databases.sql и до db-push, схема не тронута,
# прод остался на прежнем образе. Но выкатка не состоялась, а «нет снимка —
# нет выкатки» не должно означать «нет выкатки никогда».
#
# Поэтому три попытки по убыванию удобства, и выбранный путь печатается:
# молча падать нельзя, молча уезжать в другое место — тоже.
choose_snap_dir() {
  if mkdir -p "$SNAP_DIR" 2>/dev/null && [ -w "$SNAP_DIR" ]; then
    return 0
  fi

  # `sudo -n` — без пароля и без ожидания ввода: сессия выкатки
  # неинтерактивна, и обычный `sudo` в ней просто повис бы до таймаута.
  if sudo -n mkdir -p "$SNAP_DIR" 2>/dev/null &&
    sudo -n chown "$(id -u):$(id -g)" "$SNAP_DIR" 2>/dev/null &&
    [ -w "$SNAP_DIR" ]; then
    echo "снимки: каталог создан через sudo — $SNAP_DIR"
    return 0
  fi

  SNAP_DIR="$FALLBACK_DIR"
  if mkdir -p "$SNAP_DIR" 2>/dev/null && [ -w "$SNAP_DIR" ]; then
    echo "⚠️  Штатный каталог недоступен на запись — снимки идут в $SNAP_DIR"
    echo "   Чтобы вернуть их к остальным копиям, на сервере однократно:"
    echo "   sudo mkdir -p /opt/microgreen/backups/predeploy && sudo chown \$USER: /opt/microgreen/backups/predeploy"
    return 0
  fi

  return 1
}

# Штатный путь запоминаем ДО выбора: третья попытка уже переписала
# SNAP_DIR запасным, и сообщение об отказе назвало бы один и тот же
# каталог дважды — человек пошёл бы чинить не то место.
WANTED_DIR="$SNAP_DIR"
if ! choose_snap_dir; then
  echo "❌ Некуда положить снимок: ни $WANTED_DIR, ни $FALLBACK_DIR не пишутся."
  exit 1
fi

# ── Место проверяем ТАМ, ГДЕ ЛЯЖЕТ ДАМП ───────────────────────────────
# `df -h /var/lib/docker` в выкатке меряет диск под образы — другой раздел
# и другой вопрос.
DB_MB=$(docker exec "$PG_CONTAINER" psql -U "$PG_USER" -d "$PG_DB" -tAc \
  "SELECT (pg_database_size('$PG_DB')/1024/1024)::bigint;" | tr -d ' ')
FREE_MB=$(df -Pm "$SNAP_DIR" | awk 'NR==2 {print $4}')

# ── Обе величины обязаны быть числами ─────────────────────────────────
# `set -e` здесь НЕ страхует, и это проверено прогоном: в конвейере
# `psql … | tr` код возврата берётся у `tr`, а он доволен и пустым вводом.
# При недоступной базе DB_MB оказывался пустым, `$((DB_MB + 512))`
# сворачивалось в 512, и проверка места отвечала «хватает» — то есть
# рапортовала об исправности, ничего не измерив.
for pair in "размер базы:$DB_MB" "свободное место:$FREE_MB"; do
  what=${pair%%:*}
  value=${pair#*:}
  case "$value" in
    '' | *[!0-9]*)
      echo "❌ Не удалось измерить $what (получено: «$value»)."
      echo "   Проверьте, что контейнер $PG_CONTAINER жив и база $PG_DB на месте."
      exit 1
      ;;
  esac
done
echo "снимок: база ${DB_MB} МБ, свободно ${FREE_MB} МБ"

# Запас считаем по НЕСЖАТОМУ размеру: степень сжатия зависит от данных, и
# закладываться на неё — значит однажды упереться в полный диск на
# середине дампа.
NEED_MB=$((DB_MB + 512))
if [ "$FREE_MB" -lt "$NEED_MB" ]; then
  echo "❌ Мало места под снимок базы: нужно ${NEED_MB} МБ, есть ${FREE_MB} МБ."
  echo "   Освободите $SNAP_DIR или диск сервера и повторите."
  exit 1
fi

SNAP="$SNAP_DIR/predeploy-$(date -u +%Y%m%d-%H%M%S)-${LABEL}.sql"

# ── Пишем во временное имя ────────────────────────────────────────────
# Перенаправление создаёт файл ДО того, как pg_dump успеет отработать или
# упасть. Без этого после неудачи в каталоге оставался огрызок под
# настоящим именем — проверено прогоном на несуществующей базе: код
# возврата был честной единицей, а файл лежал и выглядел снимком.
#
# Настоящее имя появляется только у ЦЕЛОГО дампа, всё остальное убирает
# ловушка — в том числе при обрыве связи по Ctrl-C или таймауту.
PART="$SNAP.part"
trap 'rm -f "$PART"' EXIT INT TERM
docker exec "$PG_CONTAINER" pg_dump -U "$PG_USER" -d "$PG_DB" --no-owner > "$PART"

# ── Полнота, а не только код возврата ─────────────────────────────────
# Дамп, оборванный на середине, тоже оставляет файл и ненулевой размер.
# Отметка о завершении, которую пишет сам pg_dump, — единственное, что
# отличает целый снимок от обрубка.
#
# ХВОСТ БЕРЁМ С ЗАПАСОМ, и это не перестраховка. Отметка стоит НЕ
# последней строкой: свежие pg_dump дописывают за ней пустую строку и
# команду `\unrestrict <токен>`. Проверено на живом дампе: при `tail -3`
# отметка в окно не попадает, и проверка роняла бы КАЖДЫЙ вызов на
# исправном снимке. Обнаружение обрыва от ширины окна не страдает — у
# оборванного дампа отметки нет нигде.
if ! tail -20 "$PART" | grep -q "PostgreSQL database dump complete"; then
  echo "❌ Снимок оборван — отметки о завершении нет. Дальше идти нельзя."
  exit 1
fi

mv "$PART" "$SNAP"
trap - EXIT INT TERM
gzip -f "$SNAP"
ls -lh "$SNAP.gz"

# Старые вычищаем ПОСЛЕ удачного нового: иначе неудачный дамп забрал бы с
# собой ещё и предыдущий.
ls -1t "$SNAP_DIR"/predeploy-*.sql.gz 2>/dev/null | tail -n +$((KEEP + 1)) | xargs -r rm -f

echo "✅ снимок готов: $SNAP.gz"
