#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
# Что именно `db push` собирается сделать с боевой схемой.
#
# ЗАЧЕМ
#
# Прод накатывается `prisma db push --accept-data-loss`. Флаг не означает,
# что данные теряются каждый раз, — он означает, что Prisma НЕ ОСТАНОВИТСЯ
# и не спросит, когда правка окажется разрушительной. Переименовали поле в
# `schema.prisma` — Prisma видит это как «одной колонки не стало, другая
# появилась» и молча удаляет первую вместе со всем, что в ней лежало.
#
# Снимок базы перед выкаткой уже есть (`deploy/db-snapshot.sh`), и он
# обязателен. Но снимок — это путь НАЗАД, а не предупреждение: чтобы им
# воспользоваться, надо сначала заметить потерю. Замечали её по жалобе.
#
# Здесь второй рубеж и он про «вперёд»: показать SQL до его выполнения и
# остановиться, если в нём есть удаление.
#
# ЧТО СЧИТАЕТСЯ РАЗРУШИТЕЛЬНЫМ
#
#   DROP TABLE  — таблица со всем содержимым;
#   DROP COLUMN — колонка со всем содержимым.
#
# `DROP CONSTRAINT` и `DROP INDEX` сюда НЕ входят: они меняют правила, а не
# данные, и в обычной правке схемы их бывает много (переименовали связь —
# переехал внешний ключ). Останавливать выкатку на них значило бы
# превратить проверку в помеху, которую заведут привычку обходить.
#
# КАК РАЗРЕШИТЬ УДАЛЕНИЕ, КОГДА ОНО НАМЕРЕННОЕ
#
# Переменной окружения `ALLOW_SCHEMA_DATA_LOSS=1` у шага выкатки. Она
# ставится осознанно и на один раз — в отличие от `--accept-data-loss`,
# который стоит всегда и потому ничего не значит.
#
# ПОВЕДЕНИЕ ПРИ ОТКАЗЕ САМОЙ ПРОВЕРКИ
#
# Не смогли посчитать разницу — выкатка ПРОДОЛЖАЕТСЯ с предупреждением.
# Это осознанный размен: снимок уже снят, путь назад есть, а сорванная
# выкатка из-за неработающей диагностики — это день без исправлений
# ради проверки, которая сама сломалась.
#
# Запуск:  sh deploy/schema-diff.sh
# ══════════════════════════════════════════════════════════════════════
set -e

COMPOSE="${COMPOSE:-docker-compose.prod.yml}"
SCHEMA="${SCHEMA:-packages/database/prisma/schema.prisma}"

echo "🔎 Считаю, что db-push сделает со схемой…"

# Тот же контейнер, что и сам db-push: у него есть и Prisma, и DATABASE_URL.
# `|| true` — отказ диагностики не должен ронять выкатку (см. шапку).
DIFF=$(docker compose -f "$COMPOSE" run --rm --no-deps --entrypoint sh db-push -c \
  "npx prisma migrate diff \
     --from-url \"\$DATABASE_URL\" \
     --to-schema-datamodel $SCHEMA \
     --script" 2>/dev/null || true)

if [ -z "$DIFF" ]; then
  echo "⚠️  Разницу посчитать не удалось — иду дальше (снимок базы уже снят)."
  exit 0
fi

# Prisma на совпадающей схеме печатает комментарий вместо пустоты.
if echo "$DIFF" | grep -qi "empty migration"; then
  echo "✅ Схема не меняется."
  exit 0
fi

echo "── SQL, который будет применён ──────────────────────────────"
echo "$DIFF"
echo "─────────────────────────────────────────────────────────────"

DESTRUCTIVE=$(echo "$DIFF" | grep -iE "DROP[[:space:]]+TABLE|DROP[[:space:]]+COLUMN" || true)

if [ -z "$DESTRUCTIVE" ]; then
  echo "✅ Удаления данных в правке нет."
  exit 0
fi

echo ""
echo "🛑 В правке схемы есть УДАЛЕНИЕ ДАННЫХ:"
echo "$DESTRUCTIVE" | sed 's/^/    /'

if [ "$ALLOW_SCHEMA_DATA_LOSS" = "1" ]; then
  echo ""
  echo "⚠️  ALLOW_SCHEMA_DATA_LOSS=1 — продолжаю по явному разрешению."
  exit 0
fi

cat <<'WHY'

Выкатка остановлена ДО применения.

Если это переименование — Prisma его не распознаёт: она видит «одной
колонки не стало, другая появилась» и удаляет первую вместе с данными.
Перенесите данные отдельным шагом, а не полагайтесь на push.

Если удаление намеренное — повторите выкатку с ALLOW_SCHEMA_DATA_LOSS=1.
Переменная ставится на один раз и осознанно; снимок базы перед этим уже
снят (deploy/db-snapshot.sh).
WHY
exit 1
