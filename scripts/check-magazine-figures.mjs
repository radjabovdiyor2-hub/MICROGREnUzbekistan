// ════════════════════════════════════════════════════════════
// Цифры номера против манифеста публикуемых величин.
//   node scripts/check-magazine-figures.mjs [файл.html]
//
// ЗАЧЕМ
// Стоп-лист §6.2 (scripts/check-claims.mjs) ловит СЛОВА. Против выдуманной или
// съехавшей ЦИФРЫ он бессилен: «1,56 г резистентного крахмала» пройдёт гейт
// молча, потому что запрещённых слов в этой строке нет. А номер про сахар
// обещает читателю доказательность, и выдуманное среди чисел дороже опечатки.
//
// Здесь исполняется машиной то, что раньше было договорённостью: у каждой
// напечатанной величины есть источник, и он лежит в §7 doc/dossier_glycemia.md
// (документ закрытый — сюда переписаны только те строки, которым разрешено
// быть публичными) либо в таблице состава самого номера.
//
// ДВЕ СТОРОНЫ СВЕРКИ
//   1. Манифест → номер. Объявленная величина обязана быть в выпуске. Ловит
//      потерю цифры при перевёрстке.
//   2. Номер → манифест. Любое число, помеченное как утверждение (.fig-val,
//      .fig-val-s), обязано быть в манифесте. Ловит опечатку в графике и
//      цифру, взятую из закрытого досье мимо §6.4.
//
// Подпись оси, ключ панели и номер страницы утверждениями не считаются: у них
// класс .fig-tick. Граница проходит по смыслу, а не по размеру шрифта.
// ════════════════════════════════════════════════════════════
import { readFile } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILE = process.argv[2] ?? 'content/generated/shakar-01-print.html';

// Манифест. Каждая строка: величина, что это и откуда взято.
// Добавлять сюда цифру из doc/dossier_glycemia.md можно ТОЛЬКО после §6.4
// концепции: в досье есть и то, что публиковать нельзя никогда (проценты
// ингибирования, множители, дозы сульфорафана, эпидемиология).
const MANIFEST = [
  ['50', 'г свободного сахара в сутки — норма ВОЗ, ниже 10% суточной энергии', 'WHO Guideline: Sugars intake'],
  ['25', 'г — условная рекомендация ВОЗ, ниже 5% суточной энергии', 'WHO Guideline: Sugars intake'],
  ['12', 'чайных ложек — то же в ложках', 'WHO Guideline: Sugars intake'],
  ['6', 'чайных ложек — то же в ложках', 'WHO Guideline: Sugars intake'],

  ['0,64', 'г/100 г резистентного крахмала, горячий рис', 'досье §5, «автор, год»'],
  ['1,65', 'г/100 г резистентного крахмала, остывший и разогретый', 'досье §5'],
  ['152', 'ммоль·мин/л гликемического ответа, горячий', 'досье §5'],
  ['125', 'ммоль·мин/л гликемического ответа, остывший', 'досье §5'],

  ['25', 'ккал на 100 г, микс «Мягкий»', 'таблица состава, полоса 8'],
  ['32', 'ккал на 100 г, миксы «К плову» и «Крестоцветный»', 'таблица состава, полоса 8'],
  ['24', 'ккал на 100 г, микс «Цветной»', 'таблица состава, полоса 8'],
  ['3,3', 'г углеводов, «Мягкий»', 'таблица состава, полоса 8'],
  ['3,8', 'г углеводов, «К плову»', 'таблица состава, полоса 8'],
  ['4,8', 'г углеводов, «Крестоцветный»', 'таблица состава, полоса 8'],
  ['3,6', 'г углеводов, «Цветной»', 'таблица состава, полоса 8'],
  ['2,0', 'г клетчатки, «Мягкий» и «Крестоцветный»', 'таблица состава, полоса 8'],
  ['1,8', 'г клетчатки, «К плову» и «Цветной»', 'таблица состава, полоса 8'],
  ['3,2', 'г белка, «Мягкий»', 'таблица состава, полоса 8'],
  ['2,9', 'г белка, «К плову» и «Крестоцветный»', 'таблица состава, полоса 8'],
  ['2,5', 'г белка, «Цветной»', 'таблица состава, полоса 8'],
  ['103', 'мкг витамина K1, «Мягкий» — расчёт по долям культур', 'таблица состава, полоса 8'],
  ['259', 'мкг витамина K1, «К плову» — расчёт по долям культур', 'таблица состава, полоса 8'],
  ['194', 'мкг витамина K1, «Крестоцветный» — расчёт по долям культур', 'таблица состава, полоса 8'],
  ['236', 'мкг витамина K1, «Цветной» — расчёт по долям культур', 'таблица состава, полоса 8'],
];

const declared = new Set(MANIFEST.map(([v]) => v));

const html = await readFile(join(ROOT, FILE), 'utf8');
const lines = html.split(/\r?\n/);

let problems = 0;

// ── 1. Номер → манифест ──────────────────────────────────────────────
const asserted = [];
lines.forEach((line, i) => {
  for (const m of line.matchAll(/<text class="fig-val(?:-s)?"[^>]*>([^<]+)<\/text>/g)) {
    const raw = m[1].trim();
    // «50 g» → «50»: единица подписана рядом со значением и частью числа не является.
    const value = raw.replace(/\s*(?:g|г|mkg|мкг|kkal|ккал)\b.*$/i, '').trim();
    asserted.push({ value, raw, line: i + 1 });
  }
});

for (const { value, raw, line } of asserted) {
  if (declared.has(value)) continue;
  problems += 1;
  console.error(`✗ ${relative('.', FILE)}:${line}  «${raw}» напечатано как утверждение, но в манифесте его нет`);
}

// ── 2. Манифест → номер ──────────────────────────────────────────────
// Ищем в тексте, а не в разметке: величина может стоять и в таблице, и в схеме.
const text = html.replace(/<[^>]*>/g, ' ');
for (const [value, what, src] of MANIFEST) {
  const re = new RegExp(`(?<![\\d,.])${value.replace(',', '[,.]')}(?![\\d,.])`);
  if (re.test(text)) continue;
  problems += 1;
  console.error(`✗ величина «${value}» объявлена в манифесте, но в номере её нет`);
  console.error(`    ${what} · ${src}`);
}

if (problems) {
  console.error(`\n✗ расхождений: ${problems}.`);
  console.error('  Цифра в публичном номере обязана иметь источник: §7 doc/dossier_glycemia.md');
  console.error('  или таблицу состава. Новая величина — сначала в манифест, потом в вёрстку.');
  process.exit(1);
}

console.log(`✓ ${asserted.length} утверждений номера сверены с манифестом (${MANIFEST.length} величин).`);
