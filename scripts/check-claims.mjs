// ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ СКРИПТ
// Правило «никаких заявлений о лечебных и оздоровительных свойствах» живёт
// в комментариях к nutritionDb.ts, defaults.ts и balans/page.tsx. Комментарий
// не останавливает правку: в §6.3 концепции перечислено, что такие
// формулировки уже один раз просочились в каталог, JSON-LD и промпт продавца,
// и их вычищали вручную. Здесь то же правило исполняется машиной.
//
// ЧТО ПРОВЕРЯЕТСЯ
// Публичный контур: номер журнала, постеры, тексты публикаций, статические
// выпуски в apps/web/public/magazine. Закрытые документы (doc/*.md) — НЕ
// проверяются: там наука называется своим именем, и это законно, потому что
// они не являются рекламой и не публикуются.
//
// Выход 1 при любом совпадении. Это гейт, а не советчик.
// ════════════════════════════════════════════════════════════
import { readFile } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { glob } from 'node:fs/promises';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Публичный контур. Закрытые doc/*.md сюда намеренно не входят.
const TARGETS = [
  'content/generated/shakar-01-print.html',
  'content/posters/*.html',
  'content/posters/captions.md',
  'apps/web/public/magazine/shakar-01.html',
  // Рецепты — тоже публичный контур: их текст рендерится на /recipe/<slug>
  // и попадает в JSON-LD страницы. Сюда сверка не заходила, хотя именно
  // рецепт — то место, где «полезно при» просится в текст само собой.
  'packages/database/prisma/seed-recipe*.ts',
  // Прайс и каталог — не «внутренние файлы»: это те самые PDF-макеты, которые
  // владелец отдаёт клиентам, и они же отдаются сайтом по /catalog/*.html.
  // Сюда сверка не заходила, и «детокс-наборы» пролежали в баннере каталога
  // ровно столько, сколько существует гейт.
  'apps/web/public/catalog/*.html',
  // SEO_KEYWORDS уходит в metadata.keywords корневого макета, то есть
  // публикуется на КАЖДОЙ странице сайта. «detoks» и «детокса» стояли там же.
  'apps/web/src/lib/seo/*.ts',
  // Описания и панель состава товаров: отсюда текст попадает в карточку
  // витрины через enrich.ts и nutritionDb.ts. §6.3 называет оба файла среди
  // тех, куда запрещённые формулировки уже один раз просочились.
  'packages/database/prisma/enrich.ts',
  'apps/web/src/lib/nutrition/*.ts',
  // Страница метода — то, куда ведёт QR с задней обложки номера.
  'apps/web/src/app/balans/page.tsx',
  'apps/web/src/components/balans/*.tsx',
];

// Стоп-список §6.2. Ключ — что ищем, значение — чем это плохо.
// Границы слов не ставим: «диабетик», «диабетический», «профилактика» должны
// ловиться так же, как корень.
//
// ⚠️ ОКОНЧАНИЕ СЛОВА — `\p{L}*`, А НЕ `\w*`.
// В JavaScript `\w` — это ровно [A-Za-z0-9_], кириллицу он не берёт даже с
// флагом `u`. Из-за этого `снижа\w*\s+сахар` требовал пробел сразу после
// «снижа» и не совпадал ни со «снижает сахар», ни со «снижают», ни с
// «понижает уровень сахара», ни с «нормализует сахар». Три правила стоп-листа
// не срабатывали НИ РАЗУ — при том, что §6.3 называет «Контролирует уровень
// сахара в крови» среди формулировок, которые уже один раз просочились в
// nutritionDb.ts и вычищались руками. Гейт, поставленный ровно против этого,
// был к этому слеп. Проверять правки здесь только подстановкой заведомо
// запрещённой фразы — зелёный прогон сам по себе ничего не доказывает.
const W = '\\p{L}*';

const BANNED = [
  [/диабет/iu, 'заявление о специальном назначении — §6.2'],
  [/diabet/iu, 'то же латиницей: qandli diabet / diabetes'],
  [/qand kasal/iu, 'то же по-узбекски'],
  [new RegExp(`снижа${W}\\s+(?:уровень\\s+)?сахар`, 'iu'), '«снижает сахар» — заявление о свойстве'],
  [new RegExp(`понижа${W}\\s+(?:уровень\\s+)?сахар`, 'iu'), '«понижает сахар» — заявление о свойстве'],
  [/shakarni\s+kamaytir/iu, '«снижает сахар» по-узбекски'],
  [new RegExp(`нормализу${W}\\s+(?:уровень\\s+)?сахар`, 'iu'), '«нормализует сахар» — заявление о свойстве'],
  // Именно эта формулировка перечислена в §6.3 как уже просочившаяся,
  // а отдельного правила против неё в стоп-списке не было.
  [new RegExp(`контролиру${W}\\s+(?:уровень\\s+)?сахар`, 'iu'), '«контролирует сахар» — заявление о свойстве, §6.3'],
  [/лечит|излечива|исцеля/iu, 'заявление о лечении болезни'],
  [/davola\w*\s+xossa/iu, 'заявление о лечебных свойствах по-узбекски'],
  [/профилактик/iu, 'заявление о снижении риска болезни'],
  [/детокс|detoks/iu, 'недоказуемый claim, вычищен в §6.3'],
  [new RegExp(`для\\s+диабетик|диабетик${W}\\s+для`, 'iu'), 'название специального назначения'],
  // ⚠️ ГРАНИЦА СЛОВА — `(?!\p{L})`, А НЕ `\b`, ПО ТОЙ ЖЕ ПРИЧИНЕ.
  // `\b` определяется через `\w` = [A-Za-z0-9_], поэтому после кириллической
  // «з» границы не возникает никогда: «в 40 раз», «в 3 раза», «в 20–50 раз»
  // не совпадали ни разу. Правило заведено коммитом 76aa6f6 специально, чтобы
  // «в 40 раз» больше не попало в выпуск, — и всё это время не ловило ничего.
  // Диапазон добавлен потому, что источник множителя в досье записан именно
  // так: «в 20–50 раз больше глюкорафанина», и без него правило слепо к тому
  // самому виду, в котором цифра просится в текст.
  [/в\s+\d+(?:\s*[–—-]\s*\d+)?\s*(?:раз|раза)(?!\p{L})/iu, 'сравнительный множитель без протокола испытаний'],
  [/\d+\s*marta\s+(?:ko[’'`]p|foydali)/iu, 'сравнительный множитель по-узбекски'],
  [new RegExp(`замен${W}\\s+(?:лекарств|метформин|инсулин)`, 'iu'), 'заявление о замене терапии'],
];

// Правила, зависящие от контекста строки: сама по себе величина законна,
// запрещает её соседство со словом об эффекте.
//
// §6.2 запрещает «любые проценты без протокола испытаний», но буквальный
// запрет процента сломал бы номер на законных величинах: доли культур в миксе
// (35 %/20 %/15 %), скидки подписки (−5 %/−10 %) и норма ВОЗ («< 10 % суточной
// энергии») — это состав, цена и чужой норматив, а не заявление о свойстве.
// Разделяет их не число, а глагол рядом с ним. Поэтому процент ловится только
// в компании слова об эффекте: «усвоение на 37 %», «ингибирование 60,5 %»,
// «риск ниже на 17 %» — ровно те формы, в которых цифра из закрытого досье
// просится в публичный текст.
// Словарь двуязычен намеренно: номер набран узбекской латиницей и русским
// параллельно, и правило, знающее только кириллицу, пропустило бы ровно
// половину номера — ту, которую читатель видит первой.
const EFFECT = 'снижа|понижа|повыша|увеличива|ускоря|замедля|усваива|усвоен|'
  + 'биодоступ|ингибир|подавля|улучша|защища|укрепля|восстанавлива|'
  + 'эффективн|польз|риск|заболева|смертност|'
  + 'kamaytir|oshir|tezlash|so[’\'`]?rilish|samara|foyda|xavf|kasallik';

const IN_CONTEXT = [
  [
    /\d+(?:[.,]\d+)?\s*%/u,
    new RegExp(EFFECT, 'iu'),
    'процент эффекта без протокола испытаний — §6.2',
  ],
];

// Исключения: строки, где совпадение допустимо и обосновано в самом файле.
// Любое исключение обязано появляться здесь вместе с причиной, а не тихо
// переписывать регулярку выше. Строка пропускается ЦЕЛИКОМ, по всем правилам,
// поэтому шаблон обязан быть узким — не «foyda», а именно эта формулировка.
const ALLOW = [
  // Условная рекомендация ВОЗ: ниже 5 % суточной энергии (≈ 25 г) — там, где
  // сама ВОЗ говорит о «дополнительной пользе». Процент относится к чужому
  // нормативу, а не к свойству нашего товара, и §7 досье числит эту норму
  // среди публикуемых. Правило на проценты видит здесь «foyda» рядом с «5 %»
  // и без этой строки заваливает постер на цитате из руководства ВОЗ.
  // Апостроф в исходнике — HTML-сущность `&#39;`, а не символ: шаблон обязан
  // допускать оба написания, иначе исключение не совпадёт с файлом.
  /qo(?:&#39;|[’'`])?shimcha foyda bor deb hisoblanadi/iu,
  // Историческая цитата, а не заявление. Шапки enrich.ts и nutritionDb.ts
  // ПЕРЕЧИСЛЯЮТ формулировки, которые из этих файлов вычистили, — иначе
  // следующий редактор впишет их обратно, не зная, что они запрещены.
  // Шаблоны нарочно узкие: они совпадают ровно с этими двумя перечнями и
  // краснеют, если кто-то попробует спрятать за ними живой текст.
  /детоксикацию печени», «нормализует уровень сахара в крови»/iu,
  /«Сульфорафан — профилактика рака», «Контролиру/iu,
];

async function expand(pattern) {
  if (!pattern.includes('*')) return [pattern];
  const out = [];
  for await (const hit of glob(pattern, { cwd: ROOT })) out.push(hit);
  return out;
}

let checked = 0;
let hits = 0;

const patterns = [...TARGETS, ...process.argv.slice(2)];
for (const pattern of patterns) {
  for (const rel of await expand(pattern)) {
    let text;
    try {
      text = await readFile(join(ROOT, rel), 'utf8');
    } catch {
      // Файла ещё нет — это не нарушение. Гейт следит за содержимым,
      // а не за полнотой комплекта.
      continue;
    }
    checked += 1;

    text.split(/\r?\n/).forEach((line, i) => {
      if (ALLOW.some((a) => a.test(line))) return;
      for (const [re, why] of BANNED) {
        const m = line.match(re);
        if (!m) continue;
        hits += 1;
        console.error(`✗ ${relative('.', rel)}:${i + 1}  «${m[0]}» — ${why}`);
        console.error(`    ${line.trim().slice(0, 140)}`);
      }
      // Проценты вёрстки — не проценты эффекта. `style="width: 30%"` на строке
      // с заголовком «Что замедляет» давал ложное срабатывание: правило видело
      // число и глагол рядом, хотя число здесь — ширина колонки таблицы.
      // Для контекстных правил CSS убираем, а alt и aria-label оставляем: они
      // видны читателю и подчиняются §6.2 наравне с текстом.
      const prose = line.replace(/style="[^"]*"/gi, '');
      for (const [re, context, why] of IN_CONTEXT) {
        const m = prose.match(re);
        if (!m || !context.test(prose)) continue;
        hits += 1;
        console.error(`✗ ${relative('.', rel)}:${i + 1}  «${m[0]}» — ${why}`);
        console.error(`    ${line.trim().slice(0, 140)}`);
      }
    });
  }
}

if (!checked) {
  console.error('✗ не проверено ни одного файла — путь в TARGETS устарел');
  process.exit(1);
}

if (hits) {
  console.error(`\n✗ нарушений: ${hits} в ${checked} файлах.`);
  console.error('  Правило: утверждение о СВОЙСТВЕ → утверждение о СОСТАВЕ или вкусе.');
  console.error('  Основание: doc/balans_concept.md §6.2. Наука — в doc/dossier_glycemia.md, он не публикуется.');
  process.exit(1);
}

console.log(`✓ ${checked} файлов публичного контура — стоп-список §6.2 чист.`);
