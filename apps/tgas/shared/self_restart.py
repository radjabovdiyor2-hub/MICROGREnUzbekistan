"""
♻️ ПЕРЕЗАПУСК БОТА — без доступа к Docker
==========================================
Владелец видит в «Здоровье ботов», что бот не отвечает, и не может ничего
сделать: перезапуск жил только в SSH на сервере.

ПОЧЕМУ НЕ ЧЕРЕЗ DOCKER

Очевидный путь — дать боту сокет Docker и командовать контейнерами. Это
самый привилегированный доступ в стеке: сокет равносилен root на хосте, и
бот, которым управляет языковая модель, получил бы право останавливать что
угодно, включая базу и nginx. Комментарий в `docker-compose.prod.yml` такой
доступ обещает, но в `volumes:` его нет — и хорошо, что нет.

КАК ЗДЕСЬ

У всех ботов `restart: unless-stopped`. Значит контейнер, чей процесс
завершился, Docker поднимает сам. Боту достаточно выйти — никаких новых
прав не нужно вовсе.

ЧЕГО ЭТОТ СПОСОБ НЕ УМЕЕТ

Поднять бота, который УЖЕ мёртв: команду принимает живой процесс. Но такой
случай Docker разбирает и без нас — упавший контейнер перезапускается сам.
Настоящая польза здесь в другом: перечитать настройки, оживить зависший
цикл, применить новую модель — то есть случаи, когда процесс жив, а
работает неправильно.
"""

from __future__ import annotations

import asyncio
import logging
import os
from typing import Any, Dict

logger = logging.getLogger(__name__)

#: Сколько ждать перед выходом.
#:
#: Ответ по шине пишется в файл ПОСЛЕ возврата из обработчика. Выйди мы
#: сразу — вызывающий не получил бы ничего и ждал бы до таймаута, а команда
#: выглядела бы не сработавшей при том, что бот честно перезапустился.
GRACE_SECONDS = 3


async def _exit_soon(bot_name: str, reason: str) -> None:
    await asyncio.sleep(GRACE_SECONDS)
    logger.warning("RESTART: %s выходит по команде (%s)", bot_name, reason)
    # `os._exit`, а не исключение: у бота работают слушатели шины,
    # планировщик и polling aiogram, и любой из них может проглотить
    # обычное завершение. Код 0 — это штатный выход, и `unless-stopped`
    # поднимет контейнер обратно.
    os._exit(0)


def handler(bot_name: str):
    """Обработчик действия `restart_self` для шины ботов.

    Возвращает функцию, а не готовый обработчик: имя бота нужно в логе, и
    подставлять его на месте вызова у одиннадцати ботов значило бы одиннадцать
    шансов ошибиться.
    """

    async def restart_self(params: Dict[str, Any] | None = None) -> Dict[str, Any]:
        reason = str((params or {}).get("reason") or "запрос из админки")

        # Задача создаётся и НЕ ожидается: обработчик обязан вернуть ответ,
        # иначе вызывающий не узнает, что команда принята.
        task = asyncio.create_task(_exit_soon(bot_name, reason))
        _PENDING.add(task)
        task.add_done_callback(_PENDING.discard)

        return {
            "status": "ok",
            "message": f"{bot_name} перезапускается (через {GRACE_SECONDS} с)",
        }

    return restart_self


#: Живые задачи выхода. Без ссылки сборщик мусора может убрать задачу до
#: срабатывания — и бот пообещает перезапуск, которого не будет.
_PENDING: set = set()
