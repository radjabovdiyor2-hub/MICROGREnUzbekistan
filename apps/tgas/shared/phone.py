"""
📞 PHONE — один канон телефонного номера на весь офис
======================================================
Телефон — единственный ключ, по которому карточка клиента в CRM, пользователь
витрины и заказ склеиваются в одного человека. Пока форматов было четыре, склейка
не работала: `sales_ops` писал `+998881552557`, форма регистрации витрины —
`881552557` (последние 9 цифр), 2ГИС-лиды ложились сырой строкой из справочника,
а Instagram DM собирал номер третьим способом. Один и тот же ресторан существовал
в базе тремя карточками, и продажа каждый раз заводила четвёртую.

Канон один: **+998XXXXXXXXX**.

Две функции, и обе нужны:

- `normalize()` — то, что ПИШЕМ. Всегда канон.
- `match_tail()` — то, по чему ИЩЕМ. Последние 9 цифр, потому что в базе лежат
  исторические записи во всех четырёх форматах, и точное сравнение строк их не
  находит. Девять цифр — это узбекский номер без кода страны, то есть ровно та
  часть, которая не зависит от формата записи.

SQL-условие для поиска по любому историческому формату:

    WHERE RIGHT(regexp_replace(phone, '\\D', '', 'g'), 9) = :tail
"""

from __future__ import annotations

import re
from typing import Optional

# Код страны Узбекистана. Номер без него считаем местным.
UZ_COUNTRY_CODE = "998"

# Национальный номер: 9 цифр (2 — код оператора/города, 7 — сам номер).
UZ_NATIONAL_LENGTH = 9

# Минимум цифр, при котором строка ещё может быть телефоном. Ниже — это
# обрывок вроде «97» из «97 гороха», а не номер.
MIN_DIGITS = 7

# SQL-выражение поиска по любому историческому формату записи. Держим его
# здесь, чтобы у всех запросов было одно и то же понимание «тот же номер».
SQL_PHONE_TAIL = f"RIGHT(regexp_replace(phone, '\\D', '', 'g'), {UZ_NATIONAL_LENGTH})"


def digits(raw: Optional[str]) -> str:
    """Только цифры. `+998 88 155-25-57` → `998881552557`."""
    return re.sub(r"\D", "", str(raw or ""))


def normalize(raw: Optional[str]) -> Optional[str]:
    """
    Привести к канону `+998XXXXXXXXX`. Не телефон — `None`.

    `None` здесь значимо: он отличает «номера нет» от «номер есть, но кривой».
    Вызывающий обязан на него отреагировать, а не записать пустую строку —
    именно пустые строки в `customers.phone` и порождали карточки-двойники.
    """
    d = digits(raw)
    if len(d) < MIN_DIGITS:
        return None
    if len(d) == UZ_NATIONAL_LENGTH:  # 881552557 — местный номер без кода страны
        d = UZ_COUNTRY_CODE + d
    return "+" + d


def match_tail(raw: Optional[str]) -> Optional[str]:
    """
    Последние 9 цифр — ключ поиска по историческим записям.

    Именно этим сравнивают номера, а не нормализованной строкой: в базе лежат
    `+998 66 233-45-67`, `998662334567` и `662334567`, и все три — один клиент.
    """
    d = digits(raw)
    if len(d) < MIN_DIGITS:
        return None
    return d[-UZ_NATIONAL_LENGTH:] if len(d) >= UZ_NATIONAL_LENGTH else d


def is_valid_uz(raw: Optional[str]) -> bool:
    """Похоже ли на узбекский мобильный: `+998` и ровно 12 цифр."""
    d = digits(raw)
    return len(d) == len(UZ_COUNTRY_CODE) + UZ_NATIONAL_LENGTH and d.startswith(
        UZ_COUNTRY_CODE
    )


def format_display(raw: Optional[str]) -> str:
    """
    Для показа человеку: `+998 97 979-97-97`. Не для записи в базу.

    Нераспознанное возвращаем как есть — в сообщении лучше кривой номер, чем
    пустое место: руководитель по нему хотя бы поймёт, что данные испорчены.
    """
    canonical = normalize(raw)
    if not canonical or not is_valid_uz(canonical):
        return str(raw or "")
    d = canonical[1:]  # без «+»
    return f"+{d[:3]} {d[3:5]} {d[5:8]}-{d[8:10]}-{d[10:12]}"
