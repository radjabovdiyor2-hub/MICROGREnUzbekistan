def role_prompt(role: str) -> str:
    """Системный промпт роли: командный контекст + фирменный голос + роль.

    Появилась, потому что 24 промпта были заданы одной фразой прямо в вызове —
    `chat_completion("Ты копирайтер.", topic)`. Регулярка в check_prompts их не
    видела: она искала `system_prompt="…"`, а промпт передавали ПЕРВЫМ
    ПОЗИЦИОННЫМ аргументом. Среди них оказались обработчики личных сообщений
    HR- и analytics-бота — то есть половина ответов владельцу и кандидатам шла
    без фирменного голоса, без указания языка и без запрета выдумывать факты.

    Писать `TEAM_CONTEXT + "\n\n" + роль` руками в каждом месте — тот же
    способ разойтись, поэтому склейка одна на всех.
    """
    return f"{TEAM_CONTEXT}\n\n{role.strip()}"
