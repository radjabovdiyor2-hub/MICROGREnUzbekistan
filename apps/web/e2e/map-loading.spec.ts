import { expect, type Page } from "@playwright/test";

import { test } from "./fixtures";
import { loginAsOwner, openAdminTab } from "./adminNav";

// ══════════════════════════════════════════════════════════════════════
// Карта, пока точки не приехали.
//
// ЖАЛОБА ВЛАДЕЛЬЦА: «после выхода и повторного захода на карте исчезают
// точки». Воспроизводится так: холст рисовал ПУСТУЮ коллекцию всё время,
// пока идёт запрос со всеми его повторами. Ни легенды, ни покрытия — а
// лоток рядом уверял «Все клиенты на карте». Человек читает это как «моих
// клиентов больше нет», и читает первым делом после входа.
//
// Проверяем не скорость, а ЧЕСТНОСТЬ: пока показывать нечего, интерфейс
// обязан говорить «грузим», а не утверждать обратное.
// ══════════════════════════════════════════════════════════════════════

/** Заглушки админки: всё чужое гасим, карту держим неотвеченной. */
async function stubSlowMap(page: Page) {
  await page.route("**/api/**", (route) => route.fulfill({ json: {} }));
  await page.route("**/api/auth/password", (route) => route.fulfill({ json: { valid: true } }));
  // Запрос точек НЕ отвечает: это и есть окно, в котором карта пустовала.
  await page.route("**/api/admin/customers/map**", () => {
    /* держим открытым */
  });
}

test.describe("Карта, пока точки не приехали", () => {
  test("не утверждает «все клиенты на карте», пока их нет", async ({ page }) => {
    await stubSlowMap(page);
    await loginAsOwner(page);
    await openAdminTab(page, "Клиенты");
    await page.getByRole("button", { name: "Карта" }).first().click();

    // Лоток «без координат» пуст в двух совершенно разных случаях: все
    // расставлены и ничего не загружено. Пока идёт загрузка — второй.
    await expect(page.getByText("Загружаем клиентов…")).toBeVisible({ timeout: 15_000 });
    await expect(page.getByText("Все клиенты на карте")).toHaveCount(0);
  });
});
