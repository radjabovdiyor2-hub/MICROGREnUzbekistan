import { NextResponse } from 'next/server';

import { drainOffice } from '@/lib/office/outbox';

// ══════════════════════════════════════════════════════════════════════
// Разбор очереди «витрина → AI-офис» по расписанию.
//
// Основной толчок очереди даёт сама касса: каждая продажа и каждый возврат
// после ответа зовут `drainOffice`. Этого достаточно, пока в лавке торгуют.
// Но если офис лёг под вечер, а следующий чек будет утром, застрявшая
// привязка чека к клиенту проваляется всю ночь — при том, что чинить её
// уже нечего, надо просто повторить.
//
// Дверь закрыта правилом `/api/inventory/cron` (access: ADMIN) в middleware,
// то есть внешний планировщик ходит сюда с `Authorization: Bearer $BOT_SECRET`
// — тем же ключом, что и остальные его вызовы. Своей проверки здесь нет
// намеренно: второй механизм авторизации разошёлся бы с первым.
// ══════════════════════════════════════════════════════════════════════

export async function GET() {
  const { sent, pending } = await drainOffice();
  return NextResponse.json({ ok: true, sent, pending });
}
