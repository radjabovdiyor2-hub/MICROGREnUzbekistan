import { prisma } from '@repo/database';

// ══════════════════════════════════════════════════════════════════════
// Чем подтверждаем слова на странице для ресторанов.
//
// ОТЗЫВОВ ШЕФОВ ЗДЕСЬ НЕТ И НЕ БУДЕТ, пока их не принесёт владелец с
// разрешением на публикацию. Сочинённая цитата с названием заведения —
// это подделка, а не текст; закупщик, который позвонит в названный
// ресторан, узнает об этом первым.
//
// Вместо цитат — проверяемые числа: сколько заведений с нами работают, с
// какого года и сколько поставок в неделю стоит в графике.
//
// ГЛАВНАЯ ЛОВУШКА ЭТОГО ФАЙЛА. В таблице `customers` больше двух тысяч
// заведений, и почти все собраны ботами из 2ГИС как ЛИДЫ для обзвона
// (`status: 'lead'`, `source: 'field'`/сборщики). Посчитать их и написать
// «нас выбрали 2000 заведений» — прямая ложь, и заметить её по коду
// нельзя: запрос выглядит правильным. Поэтому фильтр по статусу здесь
// обязателен и закрыт тестом.
// ══════════════════════════════════════════════════════════════════════

/** Статусы, означающие «действительно наш клиент», а не «нашли в справочнике». */
export const REAL_CLIENT_STATUSES = ['active', 'vip'] as const;

export interface B2bFacts {
  /** Сколько заведений закупаются. */
  venues: number;
  /** Год первой закупки — «работаем с …». `null`, если клиентов нет. */
  since: number | null;
  /** Сколько регулярных поставок в неделю стоит в графике. */
  weeklyDeliveries: number;
}

/**
 * Ниже этого числа факт не показываем.
 *
 * «Нас выбрали 2 заведения» — честно, но работает против нас, а округлять
 * или приукрашивать нельзя. Значит, молчим до тех пор, пока число не
 * начнёт говорить само за себя.
 */
export const MIN_VENUES_TO_SHOW = 5;

/** Стоит ли вообще показывать блок фактов. */
export function factsWorthShowing(facts: B2bFacts): boolean {
  return facts.venues >= MIN_VENUES_TO_SHOW;
}

export async function loadB2bFacts(): Promise<B2bFacts> {
  // Не `as const`: Prisma ждёт изменяемый `string[]` в `in`, а
  // замороженный кортеж туда не подходит.
  const where = {
    customerType: 'b2b',
    status: { in: REAL_CLIENT_STATUSES.map(String) },
    deletedAt: null,
  };

  const [venues, earliest, weeklyDeliveries] = await Promise.all([
    prisma.customer.count({ where }),
    prisma.customer.findFirst({
      where,
      select: { createdAt: true },
      orderBy: { createdAt: 'asc' },
    }),
    // Регулярные заезды считаем по графику, а не по выполненным рейсам:
    // график — это обязательство, которое мы держим каждую неделю, а
    // рейсы за прошлую неделю зависят от праздников и погоды.
    prisma.visitSchedule.count({ where: { customer: where } }),
  ]);

  return {
    venues,
    since: earliest ? earliest.createdAt.getFullYear() : null,
    weeklyDeliveries,
  };
}
