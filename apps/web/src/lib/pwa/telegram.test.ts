import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

// ══════════════════════════════════════════════════════════════════════
// Сторож: SDK Telegram грузится только тем, кто пришёл из Telegram.
//
// Файл весит 114 КБ и стоял в общей разметке — значит приезжал каждому
// посетителю сайта и на каждой странице, включая экран входа в админку,
// где от него нет никакой пользы. Внутри мини-приложения он нужен: на нём
// держатся отклик кнопок, тема и кнопка «назад».
//
// Проверка смотрит на исходник: подмена тега на условную вставку легко
// откатывается обратно одной строкой, а заметить это в браузере можно
// только специально измеряя вес страницы.
// ══════════════════════════════════════════════════════════════════════

const LAYOUT = readFileSync(join(process.cwd(), 'src/app/layout.tsx'), 'utf8');

describe('SDK Telegram', () => {
  it('не подключён тегом без условия', () => {
    // Иначе 114 КБ уедут всем, включая тех, кто открыл сайт в браузере.
    expect(LAYOUT).not.toMatch(/<script[^>]*src="https:\/\/telegram\.org/);
  });

  it('вставляется по признаку `tgWebApp` в адресе', () => {
    expect(LAYOUT).toContain('tgWebApp');
    expect(LAYOUT).toContain('telegram.org/js/telegram-web-app.js');
  });

  it('признак запоминается на вкладку — внутренние переходы адрес меняют', () => {
    // Telegram дописывает параметры только на первом шаге. Без памяти SDK
    // пропадал бы при первом же переходе внутри мини-приложения.
    expect(LAYOUT).toContain('sessionStorage');
  });

  it('вставка не роняет страницу, если хранилище закрыто', () => {
    // В приватном режиме обращение к sessionStorage бросает исключение.
    // `[\s\S]` вместо флага `s`: он требует цели ES2018, а сборка её не
    // ставит. `tsc --noEmit` при этом молчал — проверка типов у сборки
    // строже, и падала только она.
    expect(LAYOUT).toMatch(/try\{[\s\S]*tgWebApp/);
    expect(LAYOUT).toMatch(/catch\(e\)\{\}/);
  });
});
