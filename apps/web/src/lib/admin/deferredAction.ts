// Отложенное действие с отменой.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Отмена удаления в админке держится на одном
// свойстве: «выполнено», «отменено» и «доведено при уходе» — три исхода,
// и случиться должен РОВНО ОДИН. Ошибка здесь не косметическая: два
// исхода подряд означают либо удаление после нажатия «Отменить», либо
// удаление дважды.
//
// Внутри провайдера это свойство проверить нечем — там React. Здесь оно
// проверяется напрямую, а провайдер остаётся тонким.
//
// ПОЧЕМУ ОТМЕНА НАСТОЯЩАЯ, А НЕ «УДАЛИЛИ И ВЕРНЁМ». Действие не
// выполняется, пока идёт отсчёт. Косметическая отмена — та, что удаляет
// сразу и потом восстанавливает, — хуже её отсутствия: восстановить
// получится не всё и не всегда, а полагаться на неё начнут.
// ══════════════════════════════════════════════════════════════════════

/** Таймеры. Подменяются в тестах, чтобы не ждать секунды по-настоящему. */
export interface Timers {
  set: (fn: () => void, ms: number) => number;
  clear: (id: number) => void;
}

const REAL_TIMERS: Timers = {
  set: (fn, ms) => window.setTimeout(fn, ms),
  clear: (id) => window.clearTimeout(id),
};

export interface DeferOptions {
  /** Через сколько выполнить, если не отменят. */
  delayMs: number;
  /** Позвать, когда действие выполнено (по времени или досрочно). */
  onDone?: () => void;
  /** Позвать, когда действие отменено. */
  onCancelled?: () => void;
  timers?: Timers;
}

export interface Deferred {
  /** Передумали: действие не выполнится. */
  cancel: () => void;
  /** Довести до конца прямо сейчас — например, при уходе с экрана. */
  flush: () => void;
  /** Уже решено: выполнено или отменено. */
  settled: () => boolean;
}

/**
 * Выполнить `run` через `delayMs`, оставив возможность передумать.
 *
 * Исход ровно один: либо `run` выполнился (по времени или через `flush`),
 * либо отменён. Повторные вызовы обоих методов после этого ничего не
 * делают — это и есть главное свойство модуля.
 */
export function deferAction(run: () => void, options: DeferOptions): Deferred {
  const timers = options.timers ?? REAL_TIMERS;
  let settled = false;

  const timer = timers.set(() => {
    if (settled) return;
    settled = true;
    run();
    options.onDone?.();
  }, options.delayMs);

  return {
    settled: () => settled,

    cancel: () => {
      if (settled) return;
      settled = true;
      timers.clear(timer);
      options.onCancelled?.();
    },

    flush: () => {
      if (settled) return;
      settled = true;
      timers.clear(timer);
      run();
      options.onDone?.();
    },
  };
}
