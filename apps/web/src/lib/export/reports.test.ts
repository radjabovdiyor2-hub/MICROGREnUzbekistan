import { describe, expect, it } from 'vitest';

import { REPORT_TYPES, csvCell, isReportType } from './reports';

// ══════════════════════════════════════════════════════════════════════
// Склейка ячейки CSV.
//
// Значения оборачивались в кавычки, а кавычка ВНУТРИ значения ничем не
// экранировалась: товар «Руккола "Экстра"» разваливал строку, и Excel читал
// остаток как новые колонки. Файл при этом скачивался и выглядел нормально
// до того момента, как по нему считали деньги.
// ══════════════════════════════════════════════════════════════════════

describe('ячейка CSV', () => {
  it('удваивает кавычку внутри значения', () => {
    // RFC 4180: иначе строка разъезжается по колонкам.
    expect(csvCell('Руккола "Экстра"')).toBe('"Руккола ""Экстра"""');
  });

  it('не боится запятой и перевода строки', () => {
    expect(csvCell('Самарканд, ул. Регистан')).toBe('"Самарканд, ул. Регистан"');
    expect(csvCell('первая\nвторая')).toBe('"первая\nвторая"');
  });

  it('пустое значение остаётся пустой ячейкой, а не словом undefined', () => {
    expect(csvCell(null)).toBe('""');
    expect(csvCell(undefined)).toBe('""');
  });
});

describe('виды отчётов', () => {
  it('знает те, что были, и те, что добавились', () => {
    // Клиенты, заказы и финансы — то, что чаще всего просят
    // унести в таблицу, и чего выгрузить было нельзя.
    for (const t of ['inventory', 'debts', 'movements', 'sales', 'customers', 'orders', 'finance']) {
      expect(isReportType(t), t).toBe(true);
    }
    expect(REPORT_TYPES).toHaveLength(7);
  });

  it('чужой тип отвергает', () => {
    // Иначе `buildReport` ушёл бы в ветку, которой нет.
    expect(isReportType('drop-table')).toBe(false);
  });
});
