import { describe, expect, it } from 'vitest';

import { SETTINGS } from './settingsData';

// ══════════════════════════════════════════════════════════════════════
// Рубильник ИИ: свойства, потеря которых ничего не ломает СРАЗУ.
//
// Выключатель гасит три независимых пути к модели: боты офиса
// (shared/ai_engine.py читает app_settings напрямую), витрину
// (lib/ai/openaiClient.ts) и магазинного бота. Последний — отдельный модуль
// и ходит в витрину только по HTTP, поэтому единственный его источник —
// поле `aiEnabled` в публичном /api/config.
//
// Отсюда риск, ради которого написан файл: если у ключа однажды уберут
// `publicKey`, он пропадёт из /api/config, магазинный бот НЕ УЗНАЕТ о
// выключении и продолжит тратить деньги. Ничего не упадёт, тесты останутся
// зелёными, а счёт придёт в конце месяца.
//
// То же и с умолчанием: `default: false` означал бы, что на свежей базе,
// где строки в app_settings ещё нет, ИИ выключен у всех разом — и никто не
// поймёт почему.
// ══════════════════════════════════════════════════════════════════════

describe('ключ ai.enabled', () => {
  const def = SETTINGS['ai.enabled'];

  it('существует — иначе выключать нечем', () => {
    expect(def).toBeDefined();
  });

  it('булев и включён по умолчанию', () => {
    // Умолчание «включено» держит поведение свежей базы прежним: настройка
    // уточняет работу, а не задаёт её.
    expect(def.type).toBe('boolean');
    expect(def.default).toBe(true);
  });

  it('публичный — иначе магазинный бот не узнает о выключении', () => {
    // Это и есть тихая поломка: всё работает, ничего не падает, счёт растёт.
    expect(def.publicKey).toBe(true);
  });

  it('лежит в разделе про ИИ и бюджет — там его ищут', () => {
    expect(def.category).toBe('ai');
  });

  it('подписан по-русски и по-узбекски', () => {
    expect(def.labelRu).toBeTruthy();
    expect(def.labelUz).toBeTruthy();
  });
});
