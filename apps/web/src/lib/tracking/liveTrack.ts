// ══════════════════════════════════════════════════════════════════════
// Какой кусок дня показывать на живой карте — и какая точка «текущая».
//
// ЧТО БЫЛО СЛОМАНО. Дверь брала точки дня `orderBy: at asc, take: 400` и
// объявляла последнюю из них текущей позицией. После четырёхсот крошек
// «последняя» — это четырёхсотая, а не свежая: пин замирал на месте, где
// человек был утром, а подпись «молчит N мин» росла без конца. В шапке той
// же двери написано, что показывать старую позицию как текущую значит
// врать картой; ровно это и происходило.
//
// ПОЧЕМУ СВЕЖИЕ, А НЕ ПРОРЕЖИВАНИЕ ДНЯ. Прореживание тоже чинит «текущую»
// и сохраняет утро, но это полный просмотр строк на каждый опрос — ради
// утра, которого на этом экране не спрашивают. Здесь вопрос «где он
// СЕЙЧАС»; утро живёт в отчёте дня.
//
// ОБРЕЗАНО — ЗНАЧИТ СКАЗАНО. Молча нарисовать кусок пути под подписью «с
// 02:03» — это снова карта, которая утверждает больше, чем знает.
// ══════════════════════════════════════════════════════════════════════

export interface LiveSlice<T> {
  /** По возрастанию времени: рисовальщику нужен порядок хода, а не выдачи. */
  track: T[];
  /** Самая свежая точка — она и есть «где он сейчас». */
  last: T | null;
  /** Хвост дня не поместился: показан только последний отрезок пути. */
  trimmed: boolean;
}

/**
 * Развернуть выдачу «сначала свежие» в путь и текущую точку.
 *
 * Берёт на одну строку больше предела — только чтобы отличить «ровно предел»
 * от «не поместилось». Эта лишняя строка в путь не идёт.
 */
export function chronological<T>(newestFirst: T[], max: number): LiveSlice<T> {
  const last = newestFirst[0] ?? null;
  const kept = newestFirst.slice(0, max);
  return {
    track: kept.slice().reverse(),
    last,
    trimmed: newestFirst.length > max,
  };
}
