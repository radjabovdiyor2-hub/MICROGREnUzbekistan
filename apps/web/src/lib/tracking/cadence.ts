import { MIN_INTERVAL_MS } from './pingQueue';

// ══════════════════════════════════════════════════════════════════════
// Две арифметики живого экрана: возраст молчания и частота точек.
//
// ВОЗРАСТ МОЛЧАНИЯ. Сервер считает «молчит N минут» в момент ответа, а
// экран держит этот ответ ещё 45–135 секунд, а без сети — сколько угодно.
// Показать число как есть значит утверждать «на связи» про позицию,
// которой уже несколько минут. Стареем его САМИ.
//
// ПО ПРОШЕДШЕМУ ВРЕМЕНИ, А НЕ ПО ЧАСАМ. Сравнивать метку сервера с часами
// телефона нельзя: часы на телефоне врут, и в проекте уже есть правило
// отбрасывать замеры «из прошлого» по этой причине (`pingQueue.shouldKeep`).
// Здесь считается только РАЗНИЦА локальных моментов, поэтому сдвиг часов
// на неё не влияет.
//
// ЧАСТОТА ТОЧЕК. Отвечает на вопрос, который иначе задать некому: «почему
// линия прямая». Ожидание известно — `MIN_INTERVAL_MS`, крошка каждые 45
// секунд. «Раз в девять минут» при таком ожидании означает, что сторож
// усыпляется системой, и следующий вопрос не к карте, а к телефону.
// ══════════════════════════════════════════════════════════════════════

/**
 * Состарить «молчит N минут» на время, прошедшее с получения ответа.
 *
 * `null` остаётся `null`: «не прислал ни одной точки» — это не «молчит
 * ноль минут», и превращать одно в другое значит послать чинить не то
 * (то же различие держит `presence.ts`).
 */
export function agedSilentMin(fromServer: number | null, msSinceFetch: number): number | null {
  if (fromServer === null) return null;
  const aged = fromServer + Math.max(0, msSinceFetch) / 60_000;
  return Math.round(aged);
}

/**
 * Средний промежуток между точками в минутах. `null` — считать не из чего.
 *
 * Одна точка промежутка не образует: между чем и чем его мерить. Ноль
 * здесь читался бы как «шлёт непрерывно» — ровно наоборот правде.
 */
export function cadenceMin(points: number, spanMs: number): number | null {
  if (points < 2 || spanMs <= 0) return null;
  return Math.round(spanMs / (points - 1) / 60_000);
}

/** Столько минут между крошками мы ожидаем от исправного сторожа. */
export const EXPECTED_CADENCE_MIN = MIN_INTERVAL_MS / 60_000;

/**
 * Реже ожидаемого — значит сторож усыпляли.
 *
 * Порог с запасом втрое, а не «больше ожидаемого»: крошка пишется по
 * интервалу ИЛИ по смещению на 25 метров, поэтому у человека, который
 * полдня просидел у одного клиента, промежуток законно больше минуты.
 */
export function cadenceIsPoor(cadence: number | null): boolean {
  return cadence !== null && cadence > EXPECTED_CADENCE_MIN * 3;
}
