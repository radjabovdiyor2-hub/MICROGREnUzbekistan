import { describe, expect, it } from 'vitest';

import { MIN_INTERVAL_MS } from './pingQueue';
import { EXPECTED_CADENCE_MIN, agedSilentMin, cadenceIsPoor, cadenceMin } from './cadence';

// ══════════════════════════════════════════════════════════════════════
// Арифметика, которая решает, соврёт ли живой экран.
//
// Оба числа выглядят безобидно и оба врут молча: устаревшее «на связи» под
// позицией часовой давности и «раз в ноль минут» там, где точка всего одна.
// ══════════════════════════════════════════════════════════════════════

describe('agedSilentMin', () => {
  it('добавляет прошедшее время к серверному числу', () => {
    expect(agedSilentMin(3, 120_000)).toBe(5);
  });

  it('свежий ответ не меняет числа', () => {
    expect(agedSilentMin(7, 0)).toBe(7);
  });

  it('«не прислал ни одной точки» не превращается в «молчит ноль»', () => {
    // Это разные вещи, и звать чинить их надо по-разному: одного — включить
    // запись, другого — проверить связь.
    expect(agedSilentMin(null, 600_000)).toBeNull();
  });

  it('часы, ушедшие назад, не омолаживают молчание', () => {
    expect(agedSilentMin(10, -600_000)).toBe(10);
  });
});

describe('cadenceMin', () => {
  it('считает средний промежуток между точками', () => {
    // 41 точка за шесть часов — примерно раз в девять минут.
    expect(cadenceMin(41, 6 * 3600_000)).toBe(9);
  });

  it('одна точка промежутка не образует', () => {
    expect(cadenceMin(1, 3600_000)).toBeNull();
    expect(cadenceMin(0, 3600_000)).toBeNull();
  });

  it('нулевой промежуток времени — не повод делить на ноль', () => {
    expect(cadenceMin(10, 0)).toBeNull();
  });
});

describe('cadenceIsPoor', () => {
  it('ожидание берётся из очереди отправителя, а не переписано числом', () => {
    // Разойдись эти два числа — и экран называл бы «редко» то, что для
    // отправителя норма.
    expect(EXPECTED_CADENCE_MIN).toBe(MIN_INTERVAL_MS / 60_000);
  });

  it('раз в девять минут при ожидаемых 45 секундах — редко', () => {
    expect(cadenceIsPoor(9)).toBe(true);
  });

  it('минута-две — это норма: крошка пишется и по смещению тоже', () => {
    expect(cadenceIsPoor(1)).toBe(false);
    expect(cadenceIsPoor(2)).toBe(false);
  });

  it('считать не из чего — не повод обвинять', () => {
    expect(cadenceIsPoor(null)).toBe(false);
  });
});
