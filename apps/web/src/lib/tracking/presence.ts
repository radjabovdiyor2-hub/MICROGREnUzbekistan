import { SILENT_MIN } from './ping';

// ══════════════════════════════════════════════════════════════════════
// На связи ли человек — одно определение на витрину и на бота.
//
// ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Это решение сторожа: по нему бот пишет живому
// человеку. Ошибка здесь тихая — лишнее сообщение в законный выходной
// выглядит как работающая система, а не как поломка, и заметить её можно
// только по тому, что напоминания перестают читать. Чистая функция без
// Prisma проверяется тестом; тот же код внутри роута — не проверяется
// ничем, кроме живого дня.
// ══════════════════════════════════════════════════════════════════════

/**
 * Состояние полевого сотрудника на сейчас.
 *
 * · `off` — смены сегодня не открывал: выходной, больничный, склад.
 *   Спрашивать не о чем;
 * · `never` — смена идёт, а крошек не было ни одной: запись не включена;
 * · `silent` — крошки были и прекратились: трансляция оборвалась;
 * · `ok` — точки идут.
 */
export type PresenceState = 'off' | 'never' | 'silent' | 'ok';

/**
 * Что мы знаем о человеке прямо сейчас.
 *
 * `silentMin` — сколько минут прошло с последней крошки; `null` означает,
 * что крошек сегодня не было вовсе. Ноль и `null` — РАЗНЫЕ вещи, и
 * складывать их в одно число нельзя: первое значит «только что писал»,
 * второе — «не писал никогда».
 */
export function presenceState(
  shiftOpen: boolean,
  silentMin: number | null,
  threshold: number = SILENT_MIN,
): PresenceState {
  // СМЕНА — ГЛАВНЫЙ ПРИЗНАК. Человек без открытой смены сегодня не
  // работает, и молчание его телефона нас не касается. До этой проверки
  // сторож писал «смена не записывается» всем подряд каждый рабочий день.
  if (!shiftOpen) return 'off';
  if (silentMin === null) return 'never';
  return silentMin >= threshold ? 'silent' : 'ok';
}
