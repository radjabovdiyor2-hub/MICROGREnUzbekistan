import { prisma } from '@repo/database';

import { daysAgo } from '@/lib/localDate';
import { getNumber } from '@/lib/settings/store';

// ══════════════════════════════════════════════════════════════════════
// Срок жизни сырого трека.
//
// ЗАЧЕМ УДАЛЯТЬ. Трансляция даёт 200–400 крошек на человека в день. Сами
// по себе они нужны ровно до тех пор, пока по ним смотрят карту дня;
// дальше ценность несут стоянки, фото и плечи — а они остаются. Хранить
// поминутный маршрут человека годами — это не архив, а лишняя
// ответственность за личные данные, которые уже никому не нужны.
//
// ЧТО ОСТАЁТСЯ. Только крошки и удаляются. `field_days` с итогами,
// `track_stays`, `visit_photos` и `route_legs` не трогаем: отчёт за
// прошлый год обязан открыться и показать, у кого был человек и сколько
// пробыл, даже когда поминутного следа уже нет.
// ══════════════════════════════════════════════════════════════════════

/**
 * Стереть крошки старше срока из настроек.
 *
 * Возвращает, сколько удалено. Ошибку не поднимает наружу: чистка — фон,
 * и падать из-за неё на приёме трека нельзя.
 */
export async function purgeOldPings(): Promise<number> {
  try {
    const keepDays = await getNumber('field.trackKeepDays');
    // Ноль или мусор в настройке стёр бы весь трек разом. Настройку правит
    // человек, и опечатка в ней не должна быть разрушительной.
    if (!Number.isFinite(keepDays) || keepDays < 7) return 0;

    const cutoff = daysAgo(Math.round(keepDays));
    const { count } = await prisma.trackPing.deleteMany({ where: { at: { lt: cutoff } } });
    return count;
  } catch (error: unknown) {
    console.error('TRACKING: чистка трека не выполнена:', error);
    return 0;
  }
}
