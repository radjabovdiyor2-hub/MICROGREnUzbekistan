import { describe, expect, it, vi } from 'vitest';

vi.mock('@repo/database', () => ({ prisma: {} }));

import { byBusinessDate } from './salesLedger';

// ══════════════════════════════════════════════════════════════════════
// Отбор по деловой дате обязан находить и строки БЕЗ неё.
//
// `sold_at` нулевая намеренно: прод накатывает схему автоматическим
// `db push --accept-data-loss`, и колонка с `@default(now())` проставила бы
// момент деплоя всей истории продаж. Ценой этого решения строки живут без
// деловой даты ровно до того, как отработает заполнитель, — и всё это время
// отчёты обязаны показывать прошлую выручку, а не пустоту.
// ══════════════════════════════════════════════════════════════════════

describe('отбор по деловой дате', () => {
  const range = { gte: new Date('2026-08-01'), lt: new Date('2026-08-02') };

  it('берёт строки с деловой датой и, отдельно, без неё — по времени записи', () => {
    expect(byBusinessDate(range)).toEqual({
      OR: [
        { soldAt: range },
        { soldAt: null, createdAt: range },
      ],
    });
  });

  it('запасная ветка ограничена именно пустой деловой датой', () => {
    // Без `soldAt: null` во второй ветке строка попала бы в выборку дважды:
    // один раз по деловой дате, второй — по времени записи, и выручка
    // задвоилась бы у всего, что проведено не задним числом.
    const fallback = byBusinessDate(range).OR[1];
    expect(fallback).toHaveProperty('soldAt', null);
    expect(fallback).toHaveProperty('createdAt', range);
  });
});
