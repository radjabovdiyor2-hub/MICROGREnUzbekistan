import { setWorkerUrl } from 'maplibre-gl';

// ══════════════════════════════════════════════════════════════════════
// Где MapLibre берёт свой Web Worker.
//
// ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО. Воркер разбирает векторные тайлы, и без него
// карта рисует только фоновый слой стиля — в тёмной теме это ровный
// чёрный прямоугольник, неотличимый от «карта не подключена». Атрибуция и
// кнопки зума при этом на месте: они из главного потока.
//
// Адрес воркера MapLibre вычисляет от `import.meta.url` строкой, и
// переписать его бандлер не может. Turbopack при этом выносит воркер в
// static/media/ с хешем в имени, а его спутника maplibre-gl-shared.mjs —
// с ДРУГИМ хешем. Воркер импортирует спутника относительным путём без
// хеша, импорт уходит в 404, воркер умирает. Именно так карта и почернела
// на бою 18.08.2026.
//
// Поэтому оба файла лежат в public/maplibre/ под стабильными именами
// (кладёт scripts/copy-maplibre-worker.mjs на prebuild), а здесь мы просто
// сообщаем адрес. `setWorkerUrl` кладёт его в config.WORKER_URL, и это
// значение имеет приоритет над вычислением от import.meta.url. Путь
// same-origin, поэтому MapLibre поднимает module-воркер напрямую, без
// обходного пути через blob.
//
// Импортируется обоими холстами — админским и витринным. Оба грузятся
// через next/dynamic с ssr:false, поэтому побочный эффект на уровне
// модуля безопасен: на сервере он не выполнится.
//
// РАНТАЙМ-ПРОВЕРКИ ЗДЕСЬ НАМЕРЕННО НЕТ. Первая версия пинговала воркер
// HEAD-запросом, чтобы поймать пропавший файл. Проверка живьём показала,
// что её перехватывает service worker витрины и она падает с «Failed to
// fetch» независимо от того, есть файл или нет. То есть проверка умела
// спрятать ИСПРАВНУЮ карту за заглушкой — это хуже той поломки, от
// которой она стерегла.
//
// Пропавший файл ловится там, где и должен, — до прода:
//   • src/lib/map/worker.test.ts — сверяет, что импорт воркера совпадает
//     с именем файла, реально лежащего рядом;
//   • e2e/map.spec.ts — открывает страницу браузером и требует 200;
//   • сам scripts/copy-maplibre-worker.mjs падает, если исходников нет.
// ══════════════════════════════════════════════════════════════════════

/** Путь совпадает с тем, куда кладёт файлы scripts/copy-maplibre-worker.mjs. */
export const MAPLIBRE_WORKER_URL = '/maplibre/maplibre-gl-worker.mjs';

setWorkerUrl(MAPLIBRE_WORKER_URL);
