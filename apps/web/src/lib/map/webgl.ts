// Есть ли в этом браузере WebGL.
//
// ЗАЧЕМ СПРАШИВАТЬ ЗАРАНЕЕ. MapLibre без WebGL бросает из конструктора
// СИНХРОННО, и подписка на `error` до этого места не доживает. Все три
// карты проекта ловят это исключение — и все три показывали ровный пустой
// прямоугольник: отказ выглядел как «карта такая» и жил месяцами, потому
// что в консоль смотрит разработчик, а на экран — владелец.
//
// Спросив до создания карты, можно сказать словами. И это не setState из
// эффекта: ответ известен ещё до первой отрисовки.
//
// ПРОБА, А НЕ СПИСОК БРАУЗЕРОВ. Разбор `userAgent` врёт в обе стороны:
// WebGL выключают флагом, режут в энергосбережении и не дают в старых
// вебвью. Спрашиваем то, что нужно, у того, кто знает.
// ══════════════════════════════════════════════════════════════════════

/** Столько от документа нужно пробе — и ровно это подставляет тест. */
export interface CanvasMaker {
  createElement(tag: string): { getContext(id: string): unknown };
}

/**
 * `true` — карту поднять не получится.
 *
 * `undefined` вместо документа (сервер) — `false`: там нет ни экрана, ни
 * WebGL, и объявлять отказ в разметке, которая тут же оживёт в браузере,
 * значит соврать.
 */
export function webglMissingIn(doc: CanvasMaker | undefined): boolean {
  if (!doc) return false;
  try {
    const canvas = doc.createElement('canvas');
    return !(canvas.getContext('webgl') ?? canvas.getContext('experimental-webgl'));
  } catch (error) {
    // Сам вопрос бросил исключение — значит ответа нет, а это и есть «нет».
    console.error('[map] проба WebGL не удалась:', error);
    return true;
  }
}

/** То же, но у настоящего документа. */
export function webglMissing(): boolean {
  return webglMissingIn(typeof document === 'undefined' ? undefined : document);
}
