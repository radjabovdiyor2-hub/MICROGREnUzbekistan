// Предел выдачи списка — один на все админские роуты.
//
// ЗАЧЕМ. Тридцать списковых роутов отдавали `findMany` без `take`: сколько
// строк в таблице, столько и уедет в ответ. Пока лидов сотня, а смен
// полсотни, это незаметно; растут они молча и без потолка — заявки с сайта,
// кассовые операции, точки маршрутов копятся годами и не удаляются.
//
// Проявится это не постепенным замедлением, а разом: один запрос вытянет
// таблицу в память процесса, и упадёт не он, а весь сервер витрины вместе
// с оформлением заказов.
//
// ЧЕГО ЭТОТ ПРЕДЕЛ НЕ КАСАЕТСЯ, и это важно:
//
//   • ЗАДАЧ ПО РАСПИСАНИЮ (`cron/prepare`, `cron/print-run`,
//     `subscriptions/run`). Там `findMany` — не показ списка, а перебор
//     работы: обрезать его значит молча не выставить счёт части
//     подписчиков. Такие места остаются без предела намеренно;
//   • ЗЕРКАЛА КАТАЛОГА (`products/export`) — офис ждёт полный список, и
//     половина каталога хуже, чем отказ;
//   • ВЫГРУЗКИ СВОИХ ДАННЫХ (`users/data`) — по закону человек забирает
//     ВСЁ, а не первые пятьсот строк.
//
// Там, где список показывается человеку, пятисот строк заведомо больше,
// чем можно осмысленно прочитать глазами: у экранов есть поиск и фильтры,
// и это правильный способ добраться до нужного.
// ══════════════════════════════════════════════════════════════════════

/** Сколько строк максимум отдаёт списковый роут админки. */
export const LIST_LIMIT = 500;

/**
 * Предел из запроса: `?limit=` в разумных границах.
 *
 * Меньше единицы и мусор читаются как «по умолчанию»: отдать ноль строк
 * из-за опечатки в адресе — это пустой экран без объяснения.
 */
export function listLimit(searchParams: URLSearchParams, fallback = LIST_LIMIT): number {
  const raw = Number(searchParams.get('limit'));
  if (!Number.isFinite(raw) || raw < 1) return fallback;
  return Math.min(Math.floor(raw), LIST_LIMIT);
}
