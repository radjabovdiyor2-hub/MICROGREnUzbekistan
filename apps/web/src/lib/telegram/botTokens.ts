import { getBotToken } from '@/lib/telegramAuth';

// ══════════════════════════════════════════════════════════════════════
// Токены ботов, чьей подписи мы доверяем при входе через Mini App.
//
// ПОЧЕМУ СПИСОК, А НЕ ОДИН ТОКЕН
//
// Подпись `initData` ставит ТОТ бот, который открыл Mini App. Кнопки
// «Открыть в админке» есть теперь у восьми ботов офиса — от продаж до
// контента. Пока список состоял из Стёпана и витринного бота, подпись от
// финансов не сходилась, и человек упирался в экран пароля, не понимая
// причины: снаружи это выглядит как «кнопка не работает».
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ
//
// Дверей две — владелец (`/api/auth/telegram-admin`) и сотрудник
// (`/api/auth/telegram-staff`). Разойдись у них списки, и половина ботов
// пускала бы одних и не пускала других — молча и без единой ошибки в логе.
// ══════════════════════════════════════════════════════════════════════

/** Переменные окружения с токенами ботов офиса. Порядок = порядок перебора. */
const OFFICE_TOKEN_VARS = [
  // Стёпан первым: карточек от него больше всего, и перебор чаще всего
  // заканчивается на первой попытке.
  'STEPAN_BOT_TOKEN',
  'SALES_BOT_TOKEN',
  'SUPPORT_BOT_TOKEN',
  'HR_BOT_TOKEN',
  'FINANCE_BOT_TOKEN',
  'MARKETING_BOT_TOKEN',
  'ANALYTICS_BOT_TOKEN',
  'CONTENT_BOT_TOKEN',
] as const;

/**
 * Все токены, которыми может быть подписан вход.
 *
 * Витринный бот идёт последним: он открывает магазин, а не админку, и
 * попадает сюда только потому, что тоже умеет показать Mini App.
 */
export function trustedBotTokens(): string[] {
  const office = OFFICE_TOKEN_VARS.map((name) => process.env[name]);
  return [...office, getBotToken()].filter((token): token is string => Boolean(token));
}
