import { publish } from '@/lib/realtime/bus';
import { detach } from '@/lib/background';
import { notifyOfficeCatalog } from '@/lib/office/client';
import { revalidateCatalog, revalidateProduct } from './revalidate';

// ══════════════════════════════════════════════════════════════════════
// «Каталог изменился» — одно событие, три получателя.
//
// У изменения товара три независимых потребителя, и каждый узнавал о нём
// по-своему (а точнее, не узнавал):
//
//   1. Открытые экраны админки — не узнавали вовсе. Realtime не было,
//      у товаров не было даже опроса: до F5 список оставался прежним.
//   2. Публичная витрина — узнавала через час. `/catalog/[category]`
//      объявлен `force-static` + `revalidate = 3600`, и ни одна мутация
//      не сбрасывала его: снятый товар покупатель видел ещё час.
//   3. Зеркало каталога в CRM офиса — узнавало через полчаса. Синк ходит
//      фоновой петлёй с `sleep(1800)`, событий у него нет.
//
// Собрано в одну функцию НЕ ради краткости, а чтобы следующий обработчик,
// который начнёт править товары, не смог оповестить двоих из трёх. Именно
// так и вышло с каталогом: `revalidatePath` не звал никто, потому что
// звать его нужно было в пяти разных местах.
// ══════════════════════════════════════════════════════════════════════

/**
 * Сообщить всем, что каталог изменился. Зовётся ПОСЛЕ успешной записи.
 *
 * @param productId карточка, которую тоже надо сбросить; без него
 *                  обновляются только списки (правка рубрики, например).
 */
export function productsChanged(productId?: string): void {
  // 1. Открытые экраны — мгновенно, через SSE.
  publish('products', 'inventory');

  // 2. Статические страницы витрины — на следующий заход покупателя.
  if (productId) revalidateProduct(productId);
  else revalidateCatalog();

  // 3. Зеркало в CRM офиса — в фоне: ответ офиса никого не задерживает,
  //    а его недоступность не повод отвечать админке ошибкой на успешно
  //    сохранённый товар.
  detach('синк каталога в офис', notifyOfficeCatalog());
}
