import { revalidatePath } from 'next/cache';
import { CATEGORY_SLUGS } from '@/lib/seo/categories';

// ══════════════════════════════════════════════════════════════════════
// Сброс статических страниц каталога после правки товара.
//
// ЗАЧЕМ
//
// Категорийные лендинги объявлены `force-static` + `revalidate = 3600`
// (`app/catalog/[category]/page.tsx` и его языковая копия). Это правильно
// для SEO: страница отдаётся мгновенно и одинаково поисковику и человеку.
//
// Но ни одна мутация товара их не сбрасывала. Владелец снимал товар с
// продажи — и покупатель видел его в каталоге ЕЩЁ ЧАС, мог открыть карточку
// и положить в корзину. С точки зрения владельца это выглядело как «сайт
// живёт своей жизнью»: в админке товара нет, на витрине есть.
//
// ПОЧЕМУ revalidatePath, А НЕ revalidateTag
//
// Лендинги читают Postgres напрямую через Prisma, а не через `fetch`.
// Теги вешаются на кэш `fetch` и на `unstable_cache`; ни того ни другого
// здесь нет, а заворачивать запрос в `unstable_cache` ради тега значило бы
// добавить второй слой кэша поверх ISR — с собственным сроком жизни и
// собственными способами разойтись с базой.
//
// `revalidate = 3600` остаётся как страховка: изменения мимо этого API
// (сидер, ручной SQL, восстановление из бэкапа) всё равно доедут за час.
// ══════════════════════════════════════════════════════════════════════

/**
 * Пометить каталог устаревшим. Зовётся ПОСЛЕ успешной записи товара.
 *
 * Отказ не пробрасываем: товар уже сохранён, и отвечать клиенту ошибкой
 * из-за неудавшегося сброса кэша значило бы соврать о результате. Худшее,
 * что даёт молчание, — прежний час задержки, то есть ровно то, что было.
 */
export function revalidateCatalog(): void {
  try {
    revalidatePath('/catalog');
    for (const slug of CATEGORY_SLUGS) {
      revalidatePath(`/catalog/${slug}`);
      revalidatePath(`/uz/catalog/${slug}`);
      revalidatePath(`/ru/catalog/${slug}`);
    }
  } catch (err) {
    console.error('[catalog] сброс статических страниц не удался:', err);
  }
}

/** То же плюс карточка конкретного товара. */
export function revalidateProduct(id: string): void {
  revalidateCatalog();
  try {
    revalidatePath(`/product/${id}`);
  } catch (err) {
    console.error('[catalog] сброс карточки товара не удался:', err);
  }
}
