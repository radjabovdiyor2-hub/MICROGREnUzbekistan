// ══════════════════════════════════════════════════════════════════════
// Товар, которого может уже не быть.
//
// Позиции заказов и движения склада переживают удаление товара: связь
// обнуляется (`onDelete: SetNull`), а название остаётся в снимке
// `productName` — см. комментарии у `OrderItem.productName` в схеме.
//
// Определений «как показать такую строку» напрашивалось десять — по числу
// отчётов, которые её читают. Здесь оно одно, потому что расхождение между
// ними владелец увидел бы как расхождение выручки, а не как разные подписи.
// ══════════════════════════════════════════════════════════════════════

/** Всё, что нужно, чтобы строку подписать. */
export interface SoldProductLabel {
  /** Снимок названия на момент операции. */
  productName?: string | null;
  /** Живая связь — есть, пока товар не удалён окончательно. */
  product?: { nameUz: string } | null;
}

/** Строка истории продаж: позиция заказа или движение склада. */
export interface SoldProductRef extends SoldProductLabel {
  productId: string | null;
}

/**
 * Название для отчёта: снимок важнее живой карточки.
 *
 * Порядок именно такой, а не наоборот: карточку переименовывают (и тогда
 * прошлые продажи должны остаться под прежним именем), а снимок неизменен.
 * Заглушка нужна лишь строкам, созданным до появления колонки и не дожившим
 * до `backfill-product-names.ts`.
 */
export function soldProductName(row: SoldProductLabel): string {
  return row.productName ?? row.product?.nameUz ?? "O'chirilgan tovar";
}

/**
 * Ключ для группировки по товару.
 *
 * У удалённого товара `productId` пустой, а группировать его продажи всё
 * равно нужно — иначе строки схлопнутся в одну кучу «null» вместе с другими
 * удалёнными. Ключом становится название из снимка: двух разных товаров с
 * одним именем в каталоге не бывает (`slug` уникален).
 */
export function soldProductKey(row: SoldProductRef): string {
  return row.productId ?? `deleted:${soldProductName(row)}`;
}
