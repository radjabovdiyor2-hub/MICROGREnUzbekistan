import { describe, expect, it } from 'vitest';

import { FRESH_MS, isFresh } from './frame';

// ══════════════════════════════════════════════════════════════════════
// Срок годности кадра — единственное место, где блок «Теплица прямо
// сейчас» может соврать.
//
// Картинка при этом будет настоящей: камера действительно сняла теплицу.
// Ложным будет утверждение «сейчас». Ровно так уже ошибся прошлый блок
// фермы — он показывал подлинные посты ленты под подписью, которой они не
// соответствовали, и на бою под заголовком «как мы выращиваем» висела
// фотография встречи в ООН.
//
// Такую ошибку не видит ни линтер, ни сборка, ни взгляд на страницу:
// кадр красивый, блок работает. Поэтому правило проверяется числами.
// ══════════════════════════════════════════════════════════════════════

const NOW = 1_800_000_000_000;

describe('isFresh', () => {
  it('кадр, снятый только что, живой', () => {
    expect(isFresh(NOW, NOW)).toBe(true);
  });

  it('кадр в пределах срока живой', () => {
    expect(isFresh(NOW - FRESH_MS + 1_000, NOW)).toBe(true);
  });

  it('на границе срока ещё живой', () => {
    expect(isFresh(NOW - FRESH_MS, NOW)).toBe(true);
  });

  it('кадр старше срока живым не считается', () => {
    expect(isFresh(NOW - FRESH_MS - 1_000, NOW)).toBe(false);
  });

  it('вчерашний кадр — не «сейчас»', () => {
    // Камера отвалилась ночью, а страница утром говорит «в эфире».
    expect(isFresh(NOW - 24 * 60 * 60 * 1000, NOW)).toBe(false);
  });

  it('кадр из будущего не принимается', () => {
    // Сбитые часы на устройстве у камеры сделали бы кадр вечно свежим:
    // он никогда не устареет, и блок замрёт навсегда.
    expect(isFresh(NOW + 10 * 60 * 1000, NOW)).toBe(false);
  });

  it('небольшое расхождение часов прощаем', () => {
    // Минута вперёд — обычный разбег часов, а не поломка.
    expect(isFresh(NOW + 30_000, NOW)).toBe(true);
  });

  it('срок не растягивается незаметно', () => {
    // Полчаса под словом «сейчас» — это уже другое утверждение.
    expect(FRESH_MS).toBeLessThanOrEqual(10 * 60 * 1000);
  });
});
