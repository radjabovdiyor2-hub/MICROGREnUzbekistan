// Цикл рассуждения Стёпана.
//
// Инструменты чтения выполняются прямо здесь и возвращаются модели,
// чтобы она рассуждала на настоящих данных. Инструменты записи НЕ
// выполняются никогда: они превращаются в подписанные предложения,
// которые владелец подтверждает вручную.
//
// Поставщик один — OpenAI. Запасного Gemini здесь БОЛЬШЕ НЕТ, и это то же
// решение, что в ИИ-офисе (packages/mg_ai/mg_ai/engine.py): подмена движка
// происходила молча, отличить её от работающего OpenAI было нельзя, и офис
// месяцами отвечал слабой моделью. У Стёпана цена такой подмены выше всего:
// он выбирает ИНСТРУМЕНТЫ, то есть решает, что сделать с данными компании.
// Нет ключа — честная ошибка, а не тихий ответ кем-то другим.
// ══════════════════════════════════════════════════════════════════════

import { OPENAI_API_KEY, type ChatMessage, type BrainResult } from './brainConfig';
import { runOpenAI } from './brainOpenAI';

export { aiAvailable, type ChatMessage, type BrainResult } from './brainConfig';

export async function think(messages: ChatMessage[]): Promise<BrainResult> {
  if (!OPENAI_API_KEY || OPENAI_API_KEY.length <= 10) {
    throw new Error('Не задан OPENAI_API_KEY — Стёпану нечем думать');
  }
  return runOpenAI(messages);
}
