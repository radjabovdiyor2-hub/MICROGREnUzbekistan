import { notifyCustomer } from '@/lib/notify';
import { actionButton, buttonRows } from '@/lib/telegram/adminLinks';

// ══════════════════════════════════════════════════════════════════════
// Смена, открытая НЕ в боте, доходит до Telegram.
//
// ЗАЧЕМ. Человек открыл смену в приложении — и на этом всё: бот молчит, а
// запись маршрута в Telegram включается только руками, через скрепку.
// Получалась смена без маршрута, о которой никто не напомнил.
//
// ТОЛЬКО КОГДА ОТКРЫЛИ НЕ В БОТЕ. Нажав кнопку в Telegram, человек и так
// видит ответ с той же подсказкой; второе сообщение о том же событии —
// шум, а шум перестают читать вместе с нужным.
//
// ТОКЕН — БОТА ПРОДАЖ, а не витринного. Telegram доставляет нажатие
// кнопки тому боту, чьим токеном отправлено сообщение: выбор токена и
// есть выбор обработчика. Кнопка от витринного бота до полевых
// обработчиков не дойдёт никогда.
//
// НЕ БРОСАЕТ И НЕ ЖДЁТ. Смена уже открыта на сервере; молчание Telegram
// не повод отвечать человеку ошибкой на успешное действие.
// ══════════════════════════════════════════════════════════════════════

/**
 * Как включить трансляцию геопозиции.
 *
 * Дословно совпадает с `LIVE_HINT` в `bots/sales_bot/handlers/shift_menu.py`.
 * Копия здесь потому, что между приложениями нет импортов (см. конституцию),
 * а ходить в офис ради строки значило бы поставить сообщение о смене в
 * зависимость от живости соседнего контейнера.
 *
 * ВКЛЮЧИТЬ ЗА ЧЕЛОВЕКА НЕЛЬЗЯ. Telegram разрешает запустить трансляцию
 * только владельцу телефона — ни боту, ни серверу. Поэтому здесь
 * инструкция, а не обещание.
 */
const LIVE_HINT =
  'Чтобы маршрут записывался, включите трансляцию геопозиции:\n'
  + 'скрепка → Геопозиция → «Транслировать» → 8 часов.\n\n'
  + 'Включить её за вас Telegram не разрешает никому, даже боту.';

/** Во сколько открыли смену — по местному времени, а не по UTC. */
function clock(at: Date): string {
  return `${String(at.getHours()).padStart(2, '0')}:${String(at.getMinutes()).padStart(2, '0')}`;
}

/**
 * Сказать сотруднику, что смена открыта, и напомнить про трансляцию.
 *
 * `via` — откуда открыли. `bot` не шлём: там ответ уже есть.
 */
export async function announceShiftOpen(
  telegramId: bigint | null,
  startedAt: Date,
  via: string,
): Promise<void> {
  if (!telegramId || via === 'bot') return;

  try {
    await notifyCustomer(
      telegramId,
      `▶️ <b>Смена открыта в ${via === 'web' ? 'админке' : 'приложении'}</b> — ${clock(startedAt)}.\n\n`
        + LIVE_HINT,
      // Кнопка возвращается в бота продаж и открывает список точек —
      // человеку сразу видно, куда ехать, а не только что смена идёт.
      buttonRows([actionButton('🗺 Мой день', 'field:day')]),
      process.env.SALES_BOT_TOKEN,
    );
  } catch (error: unknown) {
    console.error('[shift] не сказали сотруднику об открытой смене:', error);
  }
}

/**
 * Сказать, что смена закрыта.
 *
 * Короче, чем открытие: инструкция здесь не нужна, а вот подтверждение
 * нужно — человек закрыл смену в приложении, а трансляция в Telegram
 * продолжает идти, и о ней стоит напомнить.
 */
export async function announceShiftClose(
  telegramId: bigint | null,
  endedAt: Date,
  via: string,
): Promise<void> {
  if (!telegramId || via === 'bot') return;

  try {
    await notifyCustomer(
      telegramId,
      `🏁 <b>Смена закрыта</b> — ${clock(endedAt)}.\n\n`
        + 'Запись маршрута остановлена. Трансляцию геопозиции можно '
        + 'выключить там же, где включали.',
      undefined,
      process.env.SALES_BOT_TOKEN,
    );
  } catch (error: unknown) {
    console.error('[shift] не сказали сотруднику о закрытой смене:', error);
  }
}
