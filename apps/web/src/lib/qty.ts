import { z } from 'zod';

// ══════════════════════════════════════════════════════════════════════
// Правила количества — одно место на всю витрину.
//
// Количество стало дробным (`Decimal(10, 2)` в схеме): салаты продаются за
// килограмм, и 1.3 кг — обычная продажа, а не «1» или «2». Отсюда три
// правила, которые нельзя развести по разным файлам.
//
// 1. ШАГ НАБОРА ЗАВИСИТ ОТ ЕДИНИЦЫ. «2» само по себе не говорит, два это
//    лотка или два килограмма, а цена у них разная на порядок. Кнопка «+»
//    на кассе должна прибавлять 0.1 у весового товара и ровно 1 у штучного.
//
// 2. ДВА ЗНАКА, НЕ БОЛЬШЕ. Столько же, сколько в колонке и в зеркале
//    `crm_order_items.quantity`. Присланные три знака Postgres округлил бы
//    молча, и сумма чека перестала бы сходиться с суммой позиций.
//
// 3. СУММА ПОЗИЦИИ ОКРУГЛЯЕТСЯ РОВНО ОДИН РАЗ. Деньги целые (сумы), а
//    `1.3 × 13 000` даёт 16 900.000000000002. Если каждый отчёт округлит
//    по-своему, сохранённый `Order.total` разойдётся с суммой, которую
//    пересчитывает `lib/revenue/salesLedger`. Это ровно тот класс
//    расхождений, ради устранения которого написан salesLedger.
// ══════════════════════════════════════════════════════════════════════

/** Знаков после запятой — столько же, сколько в колонке `Decimal(10, 2)`. */
const SCALE = 2;
const FACTOR = 10 ** SCALE;

/**
 * Разумный потолок одной позиции.
 *
 * Колонка `Decimal(10, 2)` вмещает до 99 999 999.99, но такое количество —
 * это не продажа, а промах по клавиатуре. Отбиваем на входе, чтобы опечатка
 * не ушла в остаток и в выручку.
 */
export const MAX_QUANTITY = 100_000;

/**
 * Единицы, которые делятся: у них шаг 0.1.
 *
 * Список ЗАКРЫТЫЙ, и незнакомая единица получает шаг 1 — так безопаснее.
 * Ошибиться в сторону штучного товара нестрашно (продавец введёт число
 * руками), а вот дробный шаг у лотков предлагал бы продать полподноса.
 *
 * Сопоставление точное, а не по вхождению подстроки: «лоток» содержит «л»,
 * и поиск вхождением сделал бы поднос литрами.
 */
const DIVISIBLE_UNITS = new Set([
  'кг', 'kg', 'килограмм',
  'г', 'g', 'гр', 'грамм',
  '100 г', '100г', '100 гр', '100гр',
  'л', 'l', 'литр', 'litr',
]);

const normalizeUnit = (unit?: string | null): string =>
  (unit ?? '').trim().toLowerCase().replace(/\s+/g, ' ');

/** Шаг набора количества по единице товара: «кг» — 0.1, «лоток»/«шт» — 1. */
export function stepFor(unit?: string | null): number {
  return DIVISIBLE_UNITS.has(normalizeUnit(unit)) ? 0.1 : 1;
}

/** Делится ли товар с такой единицей — для подсказок в интерфейсе. */
export function isDivisible(unit?: string | null): boolean {
  return DIVISIBLE_UNITS.has(normalizeUnit(unit));
}

/**
 * Приводит количество к двум знакам.
 *
 * `0.1 + 0.2` в double даёт 0.30000000000000004, и без этого шага набранное
 * кнопками количество копило бы хвост, который затем ушёл бы в базу.
 */
export function normalizeQty(value: number): number {
  return Math.round(value * FACTOR) / FACTOR;
}

/** Количество допустимо: конечное, больше нуля, не длиннее двух знаков. */
export function isValidQty(value: number): boolean {
  if (!Number.isFinite(value) || value <= 0 || value > MAX_QUANTITY) return false;
  // Сравнение с допуском, а не на равенство: 1.3 в double чуть-чуть не 1.3,
  // и строгая проверка отбила бы честное количество.
  return Math.abs(value * FACTOR - Math.round(value * FACTOR)) < 1e-6;
}

/**
 * Сумма позиции в сумах — целое.
 *
 * ЕДИНСТВЕННОЕ место, где количество умножается на цену. Складывать надо
 * уже округлённые суммы позиций: округление общей суммы в конце дало бы
 * другой результат, и чек разошёлся бы со складским журналом.
 */
export function lineTotal(unitPrice: number, quantity: number): number {
  return Math.round(unitPrice * quantity);
}

/** Сумма нескольких позиций — с тем же правилом округления. */
export function cartTotal(items: { price: number; quantity: number }[]): number {
  return items.reduce((sum, item) => sum + lineTotal(item.price, item.quantity), 0);
}

/**
 * Количество для показа: «1.3», «2» — без хвоста «.00».
 *
 * Разделитель — точка, а не запятая, хотя интерфейс русский: рядом стоит
 * поле ввода того же числа, а в него запятую не введёшь. Две записи одного
 * количества на одном экране путают сильнее, чем нерусская точка.
 */
export function formatQty(quantity: number): string {
  return String(normalizeQty(quantity));
}

/** Количество с единицей: «1.3 кг». Единицы нет — только число. */
export function formatQtyWithUnit(quantity: number, unit?: string | null): string {
  const trimmed = (unit ?? '').trim();
  return trimmed ? `${formatQty(quantity)} ${trimmed}` : formatQty(quantity);
}

/**
 * Схема количества для API.
 *
 * Было `z.number().int().min(1)` — целые, потому что колонка была `Int`.
 * Теперь колонка дробная, но два знака остаются пределом: больше их не
 * хранит ни витрина, ни зеркало CRM.
 */
export const quantitySchema = z
  .number()
  .refine((value) => isValidQty(value), {
    message: `Количество: больше нуля, не более ${SCALE} знаков после запятой, не больше ${MAX_QUANTITY}`,
  });
