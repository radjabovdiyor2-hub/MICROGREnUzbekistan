// ══════════════════════════════════════════════════════════════════════
// Единица измерения на языке того, кто смотрит.
//
// ЗАЧЕМ. Единицы приходят из прайса (`price-list.html`) и лежат в базе
// по-русски: «кг», «лоток», «шт», «100 г». Показывались они как есть — и в
// узбекском интерфейсе цена читалась «25 000 за кг» посреди латиницы.
// Полевой продавец видит это каждый рабочий день на каждой карточке.
//
// ПЕРЕВОД ЗДЕСЬ, А НЕ В БАЗЕ. Прайс — бумага, которую владелец отдаёт
// клиентам, и он на русском; заводить вторую колонку значит держать два
// написания одного факта и однажды их разведать. Здесь же — одно место на
// весь проект: касса, каталог, карточка товара, корзина.
//
// НЕИЗВЕСТНУЮ ЕДИНИЦУ ОТДАЁМ КАК ЕСТЬ. Новая строка в прайсе не должна
// исчезать с экрана из-за того, что её забыли сюда вписать: «кг» лучше
// пустоты, а пропажа заметна только владельцу и только случайно.
// ══════════════════════════════════════════════════════════════════════

const UZ: Record<string, string> = {
  'кг': 'kg',
  'г': 'g',
  '100 г': '100 g',
  'шт': 'dona',
  'лоток': 'lotok',
  'упаковка': 'quti',
  'пучок': "bog'",
  'литр': 'litr',
  'л': 'l',
  'мл': 'ml',
  'порция': 'porsiya',
};

/** Единица словами: «кг» по-русски, «kg» по-узбекски. */
export function unitLabel(unit: string | null | undefined, lang: 'ru' | 'uz'): string {
  if (!unit) return '';
  if (lang === 'ru') return unit;
  return UZ[unit.trim().toLowerCase()] ?? unit;
}

/** Денежная единица. Отдельной функцией, потому что «сум» печатается на
 *  двух десятках экранов кассы, сводки и зарплаты: разойдись он хоть раз —
 *  и на одном экране узбека будет латиница, а на соседнем кириллица. */
export function sumLabel(lang: 'ru' | 'uz'): string {
  return lang === 'ru' ? 'сум' : "so'm";
}

/**
 * Сумма деньгами: «1 250 000 сум» / «1 250 000 so'm».
 *
 * ПЯТЬ КОПИЙ БЫЛО. Одна и та же строчка с зашитым «сум» жила в
 * AdminFinance, AdminFinanceBreakEven, AdminFinanceSummary, AdminMarginTable
 * и AdminBreakEvenVerdict — и ни одна не знала про язык читателя. Именно
 * так и расходятся написания: правишь одну, четыре остаются.
 *
 * Разделитель — неразрывный узкий пробел из `toLocaleString('ru-RU')`:
 * группировка цифр от языка интерфейса не зависит.
 */
export function formatSum(n: number, lang: 'ru' | 'uz'): string {
  return `${Math.round(n).toLocaleString('ru-RU').replace(/,/g, ' ')} ${sumLabel(lang)}`;
}

/** «за кг» / «kg uchun» — предлог тоже разный, и порядок слов тоже. */
export function perUnit(unit: string | null | undefined, lang: 'ru' | 'uz'): string {
  const label = unitLabel(unit, lang);
  if (!label) return '';
  // В узбекском послелог идёт ПОСЛЕ слова: «kg uchun», а не «uchun kg».
  return lang === 'ru' ? `за ${label}` : `${label} uchun`;
}
