// Слаги для публичных адресов.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
// Раньше slugify был написан дважды и по-разному:
//   · рецепты  — /[^a-z0-9а-яё]+/gi, то есть кириллица СОХРАНЯЛАСЬ;
//   · рестораны — /[^a-z0-9]+/g, кириллица вырезалась целиком, и слаг
//     вырождался в resto-<timestamp>.
//
// Первый вариант приводил к битым страницам: рецепт, созданный в админке с
// названием по-русски, получал слаг вида «укц» и его страница отдавала 404.
// Проверено на живом стенде: две одинаковые записи, отличается только слаг —
// латиница даёт 200, кириллица 404.
//
// Поэтому здесь ОДНА транслитерация на всех: адрес всегда ASCII, читаемый,
// и совпадает с тем, что печатается на бумаге (QR журнала ведёт на /recipe/<slug>).
// ══════════════════════════════════════════════════════════════════════

// Русская и узбекская кириллица. Многобуквенные сначала — порядок важен.
const TRANSLIT: Record<string, string> = {
  ш: 'sh', щ: 'sch', ч: 'ch', ц: 'ts', ж: 'zh', ю: 'yu', я: 'ya', ё: 'yo',
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', з: 'z', и: 'i', й: 'y',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't',
  у: 'u', ф: 'f', х: 'h', ы: 'y', э: 'e', ъ: '', ь: '',
  // узбекская кириллица
  ў: 'o', қ: 'q', ғ: 'g', ҳ: 'h',
};

/**
 * Транслитерирует и приводит к безопасному для URL виду.
 *
 * @param source   строка-источник (обычно название)
 * @param fallback префикс, если после чистки ничего не осталось
 */
export function slugify(source: string, fallback = 'item'): string {
  const lower = (source || '').toLowerCase().trim();

  let out = '';
  for (const ch of lower) {
    if (ch in TRANSLIT) out += TRANSLIT[ch];
    else out += ch;
  }

  out = out
    .replace(/[^a-z0-9]+/g, '-')   // всё остальное — в дефис
    .replace(/-{2,}/g, '-')        // схлопнуть повторы
    .replace(/^-+|-+$/g, '');      // обрезать по краям

  return out || `${fallback}-${Date.now().toString(36)}`;
}

/** Не ASCII — значит адрес сломается. Используется в проверках и подсказках. */
export function isUrlSafeSlug(slug: string): boolean {
  return /^[a-z0-9-]+$/.test(slug);
}
