import { describe, expect, it } from 'vitest';

import { counterLooksCloned } from './passkeys';

// ══════════════════════════════════════════════════════════════════════
// Счётчик подписей — единственная защита от копии ключа.
//
// Аутентификатор наращивает счётчик с каждой подписью. Пришло значение НЕ
// больше сохранённого — значит либо ту же подпись прислали повторно, либо
// ключ скопировали. И то и другое означает «не пускать».
//
// НО: платформенные аутентификаторы Apple счётчик не ведут и всегда шлют
// ноль. Потребуй мы роста без оговорки — владелец с айфона не вошёл бы
// НИКОГДА, и выглядело бы это как «Face ID не работает», а не как защита.
// Поэтому пара нулей — законная, а любое другое неувеличение — нет.
// ══════════════════════════════════════════════════════════════════════

describe('счётчик подписей ключа', () => {
  it('вырос — обычный вход', () => {
    expect(counterLooksCloned(4, 5)).toBe(false);
    expect(counterLooksCloned(0, 1)).toBe(false);
  });

  it('не вырос — повтор или клон', () => {
    expect(counterLooksCloned(5, 5)).toBe(true);
    expect(counterLooksCloned(5, 4)).toBe(true);
    expect(counterLooksCloned(1, 0)).toBe(true);
  });

  it('пара нулей законна — так ведут себя ключи Apple', () => {
    // Иначе вход по Face ID не работал бы вовсе, и объяснить это было бы
    // нечем: подпись верна, а мы отказываем.
    expect(counterLooksCloned(0, 0)).toBe(false);
  });
});
