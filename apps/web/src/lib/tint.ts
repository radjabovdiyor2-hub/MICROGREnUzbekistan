// Полупрозрачная подложка под цветную плашку.
//
// ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ СТРОКА НА МЕСТЕ
//
// На месте это писали конкатенацией: `${st.color}15` — «цвет плюс альфа
// в hex». Приём верный для литерала `#22C55E`, но все цвета статусов в
// админке — ТОКЕНЫ: `var(--success)`, `var(--warning)`, `var(--cat-7)`.
// Склейка давала `var(--success)15` — объявление, которое браузер молча
// отбрасывает целиком.
//
// Итог: одиннадцать плашек — статусы заказов, долгов, движений, посадок,
// сигналов и выручки — рисовались БЕЗ ФОНА. Ошибка тихая вдвойне: цвет
// текста рядом задан тем же токеном и работает, поэтому выглядело просто
// «бледновато», а не сломано.
//
// `color-mix` считает смешение уже после подстановки переменной, поэтому
// работает и с токеном, и с литералом. Приём подсмотрен в
// `AdminCustomerTable.tsx` — там он был написан правильно с самого начала.
// ══════════════════════════════════════════════════════════════════════

/** Доля цвета в подложке по умолчанию: читаемо и не спорит с текстом. */
const DEFAULT_PERCENT = 14;

/**
 * Подложка того же цвета, что и содержимое плашки.
 *
 * @param color любое CSS-значение цвета, включая `var(--token)`
 * @param percent доля цвета, 0–100. Остальное — прозрачность
 */
export function tint(color: string, percent: number = DEFAULT_PERCENT): string {
  return `color-mix(in srgb, ${color} ${percent}%, transparent)`;
}
