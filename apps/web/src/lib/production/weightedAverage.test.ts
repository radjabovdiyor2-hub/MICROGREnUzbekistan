import { describe, it, expect } from 'vitest';
import { weightedAverageCost } from './weightedAverage';

// Себестоимость — то, из чего считается маржа. До появления этого модуля она
// бралась из «последней закупки», то есть при каждом приходе прыгала вместе
// с ценой поставщика.

describe('средневзвешенная себестоимость', () => {
  it('усредняет закупку с остатком', () => {
    // Пример владельца: было 1 кг по 50 000, купили 1 кг по 70 000.
    expect(weightedAverageCost(1000, 50, 1000, 70)).toBe(60);
  });

  it('пустой склад принимает цену закупки как есть', () => {
    // Иначе средняя «унаследовала» бы цену от нулевого остатка и занизила
    // себестоимость первой же партии.
    expect(weightedAverageCost(0, 0, 500, 120)).toBe(120);
    expect(weightedAverageCost(0, 999, 500, 120)).toBe(120);
  });

  it('большой остаток сглаживает скачок рынка', () => {
    // Ради этого выбрана средневзвешенная, а не «по последней закупке»:
    // разовый дорогой закуп не должен обрушивать расчёт маржи.
    const avg = weightedAverageCost(10_000, 50, 100, 200);
    expect(avg).toBeCloseTo(51.49, 2);
    expect(avg).toBeLessThan(60);
  });

  it('дешёвая закупка тоже усредняется, а не заменяет цену', () => {
    expect(weightedAverageCost(1000, 100, 1000, 50)).toBe(75);
  });
});
