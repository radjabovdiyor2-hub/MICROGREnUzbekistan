import { describe, expect, it } from 'vitest';
import { unitLabel } from './growBatch';

// ══════════════════════════════════════════════════════════════════════
// Два способа выращивания в одной системе.
//
// Микрозелень растят в ЛОТКАХ на кокосовом субстрате (150 г на лоток),
// салаты — ПОШТУЧНО в стаканчиках 63 мм на агро вате (пробка на стаканчик).
// До этого слово «лотков» было вшито в текст движений склада, в подписи форм
// и в сводки бота, и партия салата описывалась лотками, которых в ней нет.
// ══════════════════════════════════════════════════════════════════════

describe('единица посадки', () => {
  it('микрозелень считается лотками', () => {
    expect(unitLabel('tray', 10)).toBe('10 лотк.');
  });

  it('салат считается стаканчиками', () => {
    expect(unitLabel('cup', 250)).toBe('250 стаканч.');
  });

  it('неизвестная единица — лотки, а не пустая строка', () => {
    // Партии, посаженные до появления способов, единицы не имеют вовсе.
    // Показать «250 » без единицы хуже, чем показать привычные лотки.
    expect(unitLabel('', 5)).toBe('5 лотк.');
  });
});
