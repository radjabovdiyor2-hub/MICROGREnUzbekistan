/**
 * Отпустить промис доживать своей жизнью, не потеряв его отказ.
 *
 * Без `.catch` невыполненный промис становится unhandled rejection, а Node
 * по умолчанию гасит на ней процесс — то есть «не блокирующее» уведомление
 * роняло бы весь сайт. Поэтому отказ обязателен к логированию, и метка
 * нужна, чтобы в журнале было видно, ЧТО именно не доехало.
 */
export function detach(label: string, work: Promise<unknown>): void {
  void work.catch((err) => {
    console.error(`[background] ${label} не доставлено:`, err);
  });
}
