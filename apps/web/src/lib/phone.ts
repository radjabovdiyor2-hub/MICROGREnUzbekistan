// Один клиент — один телефон — одна запись.
//
// Нормализация была двух видов, и оба писали в `users.phone`, который
// объявлен `@unique`:
//   · регистрация в кабинете:  `replace(/\D/g, '').slice(-9)` → «901234567»
//   · оформление заказа:       `customer.phone` как есть      → «+998901234567»
//
// Один и тот же человек становился двумя аккаунтами. В кабинете «Мои заказы»
// оказывалось пусто, приветственные баллы лежали на первой записи, кэшбэк
// считался по второй, в админке клиент двоился, а в CRM офиса уезжал
// `web_user_id` не того профиля. Каждая смена формата ввода добавляла копию.
//
// Канонический вид — E.164 без пробелов: «+998901234567». Узбекский номер
// без кода страны дополняется префиксом 998, потому что вводят и так, и так.
// ══════════════════════════════════════════════════════════════════════

const UZ_COUNTRY_CODE = '998';
const UZ_LOCAL_LENGTH = 9;

/**
 * Телефон в канонический вид. Пустая строка — если распознать не удалось:
 * вызывающий сам решает, отказать или сохранить как есть.
 */
export function normalizePhone(raw: string | null | undefined): string {
  const digits = String(raw ?? '').replace(/\D/g, '');
  if (!digits) return '';

  // «901234567» — местный номер без кода страны.
  if (digits.length === UZ_LOCAL_LENGTH) {
    return `+${UZ_COUNTRY_CODE}${digits}`;
  }

  // «998901234567» либо «8998…»/«00998…» из разных клавиатур.
  const idx = digits.indexOf(UZ_COUNTRY_CODE);
  if (idx >= 0 && digits.length - idx === UZ_COUNTRY_CODE.length + UZ_LOCAL_LENGTH) {
    return `+${digits.slice(idx)}`;
  }

  // Иностранный номер: оставляем как есть, но в одном формате.
  if (digits.length >= 10) return `+${digits}`;

  return '';
}
