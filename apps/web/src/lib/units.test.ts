import { describe, expect, it } from 'vitest';

import { perUnit, unitLabel } from './units';

// ══════════════════════════════════════════════════════════════════════
// Единица измерения на языке того, кто смотрит.
//
// Ошибка здесь не падает и не логируется: у продавца-узбека посреди
// латиницы стоит «25 000 за кг», и он читает это каждый рабочий день на
// каждой карточке. Заметить может только носитель — или этот тест.
// ══════════════════════════════════════════════════════════════════════

describe('unitLabel', () => {
  it('переводит единицы прайса на узбекский', () => {
    expect(unitLabel('кг', 'uz')).toBe('kg');
    expect(unitLabel('лоток', 'uz')).toBe('lotok');
    expect(unitLabel('шт', 'uz')).toBe('dona');
    expect(unitLabel('100 г', 'uz')).toBe('100 g');
  });

  it('по-русски оставляет как в прайсе', () => {
    // Прайс — бумага, которую владелец отдаёт клиентам. Русское написание
    // на сайте обязано совпадать с ней буква в букву.
    expect(unitLabel('кг', 'ru')).toBe('кг');
    expect(unitLabel('лоток', 'ru')).toBe('лоток');
  });

  it('неизвестную единицу отдаёт как есть, а не прячет', () => {
    // Новая строка в прайсе не должна исчезать с экрана из-за того, что её
    // забыли вписать в словарь: «ящик» лучше пустоты.
    expect(unitLabel('ящик', 'uz')).toBe('ящик');
  });

  it('пусто — пусто, а не «undefined» на карточке', () => {
    expect(unitLabel(null, 'uz')).toBe('');
    expect(unitLabel(undefined, 'ru')).toBe('');
    expect(unitLabel('', 'uz')).toBe('');
  });

  it('регистр и пробелы не мешают', () => {
    expect(unitLabel(' Кг ', 'uz')).toBe('kg');
  });
});

describe('perUnit', () => {
  it('послелог в узбекском идёт ПОСЛЕ слова', () => {
    // «uchun kg» — это не по-узбекски. Порядок слов здесь такой же
    // смысловой, как перевод самой единицы.
    expect(perUnit('кг', 'uz')).toBe('kg uchun');
    expect(perUnit('кг', 'ru')).toBe('за кг');
  });

  it('без единицы предлог не выдумываем', () => {
    expect(perUnit(null, 'uz')).toBe('');
    expect(perUnit(null, 'ru')).toBe('');
  });
});
