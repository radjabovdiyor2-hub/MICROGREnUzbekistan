import path from 'path';

// ══════════════════════════════════════════════════════════════════════
// Куда класть состояние, которое обязано пережить деплой.
//
// `.admin-password.json` и `.admin-webauthn.json` лежали в `process.cwd()`,
// то есть в `/app` — внутри слоя образа. У сервиса `web` смонтирован только
// `/data/uploads`, поэтому `docker compose up -d` с новым тегом стирал оба
// файла. Последствие хуже, чем «настройка потерялась»: `verifyPassword`
// читает файл ПЕРВЫМ, а `ADMIN_PASSWORD` из окружения — последним, так что
// после смены утёкшего пароля ближайший деплой возвращал в строй именно
// старый, утёкший. Владелец при этом видел «Parol muvaffaqiyatli
// o'zgartirildi» и считал инцидент закрытым.
//
// Каталог задаётся STATE_DIR (в проде — том). Без переменной поведение
// прежнее, чтобы локальная разработка не требовала настройки.
// ══════════════════════════════════════════════════════════════════════

export function stateFile(name: string): string {
  const dir = process.env.STATE_DIR || process.cwd();
  return path.join(dir, name);
}
