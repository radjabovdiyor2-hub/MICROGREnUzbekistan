// Суммы клиента: кто их видит.
//
// Продавцу открыли клиентов и карту — по этим адресам он ездит. Вместе с
// адресами и телефонами ему поехали бы и деньги: сколько каждое заведение
// у нас закупило, сколько на бонусном счету, на какую сумму был заказ.
// Для поездки это не нужно, а знать это должен владелец.
//
// Прячем НА СЕРВЕРЕ, а не в разметке. Убрать колонку из таблицы, оставив
// число в ответе API, — это не приватность, а её видимость: ответ смотрят
// в консоли браузера одним движением.
//
// Прячем как `null`, а НЕ как ноль. Ноль — это утверждение «закупок не
// было», и продавец, глядя на «0 сум» у постоянного клиента, сделает из
// этого вывод. `null` означает «не показываем», и разметка честно рисует
// прочерк вместо суммы.
//
// Что остаётся продавцу: состояние отношений («кому пора»), количество
// заказов, даты. Этого хватает, чтобы решить, к кому ехать сегодня.
// ══════════════════════════════════════════════════════════════════════

/**
 * Скрыты ли суммы для этой роли.
 *
 * Роль берётся из подписанной сессии, а не из параметра запроса. Владелец
 * видит всё; бот (сессии нет) — тоже: он ходит по секрету за отчётами, и
 * прятать от него значило бы сломать сводки офиса.
 */
export function hidesMoney(role: string | undefined | null): boolean {
  return role === 'SELLER' || role === 'CUSTOMER';
}

/** Сумма или «не показываем». */
export function maskSum(value: number, hide: boolean): number | null {
  return hide ? null : value;
}

/** Подпись суммы: прочерк вместо числа, когда смотреть не положено. */
export function sumLabel(value: number | null, lang: 'ru' | 'uz'): string {
  if (value === null) return '—';
  return `${new Intl.NumberFormat('ru-RU').format(Math.round(value))} ${lang === 'ru' ? 'сум' : 'soʻm'}`;
}
