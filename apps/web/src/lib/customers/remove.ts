// Удаление карточки клиента — вызов из админки.
//
// Живёт рядом с остальной логикой клиентов (card.ts, bonus.ts), а не в
// компоненте: в route.ts Next.js разрешает экспортировать только
// HTTP-обработчики, а компоненты админки держатся в пределах 200 строк.
// ══════════════════════════════════════════════════════════════════════

export interface DeleteOutcome {
  message: string;
}

/**
 * Удалить клиента по id.
 *
 * Кидает ошибку с ТЕКСТОМ СЕРВЕРА, а не общим «не удалось». Отказ здесь
 * осмысленный: клиента с заказами база не отдаёт (`crm_orders.customer_id`
 * объявлен `onDelete: Restrict`), и владелец должен прочитать именно это,
 * а не гадать, почему кнопка не сработала.
 */
export async function deleteCustomer(id: number): Promise<DeleteOutcome> {
  const res = await fetch(`/api/admin/customers?id=${id}`, { method: 'DELETE' });
  const body = await res.json().catch(() => null);
  if (!res.ok) {
    throw new Error(body?.error || 'Не удалось удалить клиента');
  }
  return { message: body?.message || 'Клиент удалён.' };
}

/** Текст подтверждения: что именно исчезнет вместе с карточкой. */
export function confirmDeleteText(name: string): string {
  return (
    `Удалить клиента «${name}» безвозвратно?\n\n` +
    'Вместе с карточкой удалятся его обращения и напоминания. ' +
    'История заказов не затрагивается: клиента с заказами удалить нельзя.'
  );
}
