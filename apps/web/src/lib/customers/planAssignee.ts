// Чей план сохраняем и чей отдаём.
//
// Три строчки, но это рубеж прав, и потому они живут отдельно и под
// проверкой. Ошибиться здесь — значит дать продавцу переписать чужой день
// или показать ему чужой; ни то ни другое не упадёт и не попадёт в логи.
//
// СОТРУДНИК ОПОЗНАЁТСЯ ИМЕНЕМ — как в `Task.assignee` и в подписи чека
// кассы: в сессии есть `name`, связи с `Employee` у неё нет.
// ══════════════════════════════════════════════════════════════════════

/**
 * Кому достанется сохраняемый план.
 *
 * Владелец назначает кому угодно, в том числе «ничей» черновик — пустой
 * строкой. Продавец сохраняет ТОЛЬКО себе: что бы он ни прислал в теле
 * запроса, план ляжет на его имя.
 */
export function resolveSaveAssignee(params: {
  isOwner: boolean;
  actor: string;
  requested: string;
}): string {
  return params.isOwner ? params.requested.trim() : params.actor;
}

/**
 * Чьи планы отдаём на чтение.
 *
 * `undefined` означает «все» и достаётся только владельцу — и только когда
 * он не спросил кого-то конкретного. Продавцу всегда подставляется он сам,
 * даже если он просит чужое имя в адресе.
 */
export function resolveReadAssignee(params: {
  isOwner: boolean;
  actor: string;
  requested: string | null;
  /**
   * «Только мой план», независимо от должности.
   *
   * ЗАЧЕМ. Баннер на карте говорит «Вам назначен объезд» и предлагает
   * взять его в работу. Он спрашивал планы БЕЗ указания чьи — а владельцу
   * отдаются все, и первым же назначенным оказывался тот, который владелец
   * только что выписал продавцу. Выглядело это так, будто система назначила
   * объезд на него самого.
   *
   * Признак ставит сам экран, а чей план — решает сервер по подписи. Иначе
   * пришлось бы слать имя телом запроса, то есть верить клиенту в вопросе
   * «чьё это».
   */
  mine?: boolean;
}): string | undefined {
  if (params.mine) return params.actor;
  if (!params.isOwner) return params.actor;
  return params.requested ?? undefined;
}

/**
 * Кем считается план: собран себе или назначен сверху.
 *
 * Владелец, собравший план СЕБЕ, — это всё тот же `self`: источник
 * описывает происхождение плана, а не должность автора.
 */
export function planSource(params: { assignee: string; author: string }): 'self' | 'owner' {
  return params.assignee === params.author ? 'self' : 'owner';
}
