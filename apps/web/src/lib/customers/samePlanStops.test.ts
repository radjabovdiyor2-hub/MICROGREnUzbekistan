import { describe, expect, it } from 'vitest';

import { samePlanStops } from './visitPlanStore';

// РЕГРЕССИЯ, найденная живой проверкой против настоящей базы.
//
// Пересохранение плана с ДРУГИМ составом не сбрасывало ни отметку об
// отправке, ни подтверждение: продавец оставался со старым списком в чате,
// а владелец видел «принял» про план, которого человек не видел. Ни одна
// проверка при этом не падала — обе записи существуют и выглядят
// согласованными.

describe('samePlanStops', () => {
  it('тот же список в том же порядке — маршрут не менялся', () => {
    // Владелец нажал «сохранить» второй раз: слать человеку то же
    // сообщение заново незачем.
    expect(samePlanStops([1, 2, 3], [1, 2, 3])).toBe(true);
  });

  it('другая точка — другой маршрут', () => {
    expect(samePlanStops([1, 2], [1, 3])).toBe(false);
  });

  it('точку добавили или убрали', () => {
    expect(samePlanStops([1, 2], [1, 2, 3])).toBe(false);
    expect(samePlanStops([1, 2, 3], [1, 2])).toBe(false);
  });

  it('переставленные местами точки — ТОЖЕ другой маршрут', () => {
    // Сравнение по множеству сочло бы их одинаковыми, и человек поехал бы
    // по порядку, которого владелец уже не задавал.
    expect(samePlanStops([1, 2, 3], [3, 2, 1])).toBe(false);
  });

  it('пустые списки совпадают', () => {
    expect(samePlanStops([], [])).toBe(true);
  });

  it('первое назначение — изменение, а не совпадение', () => {
    expect(samePlanStops([], [1, 2])).toBe(false);
  });
});
