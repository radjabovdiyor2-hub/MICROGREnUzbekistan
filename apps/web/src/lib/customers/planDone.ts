// Закрыта ли остановка объезда — одно правило на все экраны.
//
// ЧТО БЫЛО СЛОМАНО. Отметки сводились по «клиент + дата», без исполнителя.
// Значит визит ЛЮБОГО сотрудника закрывал эту точку в плане у ВСЕХ: двое
// поехали в один район, один отметился — у второго план поредел сам собой.
// Владелец видел 6 из 8 у человека, который сделал три.
//
// Это не спорный вопрос, а несогласованность внутри одного файла: соседний
// `readDayFacts` уже сужал по автору отметки, а `readDayPlans` — нет.
//
// ГДЕ ЛЕЖИТ АВТОР. В `Interaction.botName`. Поле названо по первому
// применению (бот, написавший запись), но для полевых отметок туда кладётся
// ИМЯ ЧЕЛОВЕКА — `actorOf(request).actor` в `customers/visits`. Имя же
// стоит и в `VisitPlan.assignee`, поэтому они сравнимы напрямую.
//
// СЛЕДСТВИЕ, О КОТОРОМ НАДО ЗНАТЬ: отметка владельца больше не закрывает
// точку продавца. Это верно по смыслу — владелец не ездил, — и видимым это
// делает пометка «заехал, но не отметил» на экране объездов.
// ══════════════════════════════════════════════════════════════════════

/** Отметка визита, как её читают оба вызывающих. */
export interface VisitMark {
  customerId: number | null;
  /** Кто отметил. Пусто — автор не записан, и такая отметка ничего не закрывает. */
  botName: string | null;
  distanceM: number | null;
  accuracyM: number | null;
}

/** Доказательство визита: насколько близко человек был, когда отмечался. */
export interface VisitProofValues {
  distanceM: number | null;
  accuracyM: number | null;
}

/** Ключ «чья отметка у какого клиента». Одна функция, чтобы стороны сходились. */
export function markKey(assignee: string, customerId: number): string {
  return `${assignee}:${customerId}`;
}

/**
 * Разложить отметки по паре «исполнитель + клиент».
 *
 * ПОСЛЕДНЯЯ ПО ВРЕМЕНИ, а не первая: продавец возвращается вечером и меняет
 * «не застал» на «договорились». Показывать надо итог, а не первую попытку.
 * Вызывающий обязан отдать отметки в порядке убывания времени — тогда первая
 * встреченная и есть последняя по времени.
 *
 * Доказательством ПРИЕЗДА эта отметка не служит: для приезда есть ручная
 * стоянка, у неё своё время и своя проверка расстояния.
 */
export function markIndex(visits: VisitMark[]): Map<string, VisitProofValues> {
  const out = new Map<string, VisitProofValues>();
  for (const visit of visits) {
    if (visit.customerId === null) continue;
    // Отметка без автора не закрывает ничего: иначе она закрыла бы точку
    // сразу у всех, а это ровно та поломка, ради которой файл и появился.
    if (!visit.botName) continue;
    const key = markKey(visit.botName, visit.customerId);
    if (out.has(key)) continue;
    out.set(key, { distanceM: visit.distanceM, accuracyM: visit.accuracyM });
  }
  return out;
}

/**
 * Что показывать про остановку.
 *
 * ТРИ СОСТОЯНИЯ, А НЕ ДВА. Человек, который заехал и не нажал исход, до сих
 * пор выглядел как не заехавший вовсе — и владелец не мог отличить «не был»
 * от «был, но не отметил». Это разные разговоры: первый про работу, второй
 * про кнопку.
 *
 * «Заехал» НЕ означает «выполнено»: выполнение — явная отметка человека, так
 * решил владелец. Стоянка показывается рядом, а не вместо.
 */
export type StopState = 'done' | 'arrived' | 'open';

export function stopState(done: boolean, arrivedAt: string | null): StopState {
  if (done) return 'done';
  if (arrivedAt !== null) return 'arrived';
  return 'open';
}
