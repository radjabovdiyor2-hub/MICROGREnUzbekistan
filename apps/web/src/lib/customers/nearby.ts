import { distanceKm, type RoutePoint } from './dayRoute';

// ══════════════════════════════════════════════════════════════════════
// Кто рядом с этой точкой.
//
// Самый частый вопрос в поле и единственный, на который карта до сих пор
// не отвечала: «раз уж я приехал — кто ещё в квартале?». Ответ был
// возможен только глазами, зумом и памятью, а забытый сосед — это ещё
// одна поездка через весь город на следующей неделе.
//
// Расстояние считается по прямой тем же `distanceKm`, что и длина объезда
// (гаверсинус). Дорожного расстояния у нас нет и не будет без внешнего
// маршрутизатора — а он потребовал бы и новой зависимости, и правки CSP.
// Для вопроса «пешком дойду или ехать» прямой хватает: ошибка в плотной
// застройке идёт в сторону занижения, то есть в сторону осторожности.
// ══════════════════════════════════════════════════════════════════════

/** Точка с координатами и именем — всё, что нужно для сравнения. */
export interface NearbyPoint extends RoutePoint {
  /** Что это за точка: клиента и цель показываем по-разному. */
  kind?: string;
}

export interface NearbyHit<T extends NearbyPoint> {
  point: T;
  km: number;
}

/** Сколько показываем. Список под кнопкой, а не выгрузка района. */
export const NEARBY_LIMIT = 6;

/**
 * Дальше этого — уже не «рядом», а «в городе».
 *
 * Два километра выбраны по смыслу вопроса: это ещё один заезд по пути, а
 * не отдельная поездка. Без потолка список всегда возвращал бы шесть
 * штук, и на окраине в него попадали бы точки за полчаса езды — то есть
 * «рядом» переставало бы что-либо значить.
 */
export const NEARBY_MAX_KM = 2;

/**
 * Ближайшие к точке `origin`, по возрастанию расстояния.
 *
 * Сама точка из выдачи исключается по id: расстояние до себя всегда ноль,
 * и без этого она возглавляла бы собственный список соседей.
 */
export function nearestPoints<T extends NearbyPoint>(
  points: T[],
  origin: RoutePoint,
  limit: number = NEARBY_LIMIT,
  maxKm: number = NEARBY_MAX_KM,
): NearbyHit<T>[] {
  const hits: NearbyHit<T>[] = [];

  for (const point of points) {
    if (point.id === origin.id) continue;
    const km = distanceKm(origin, point);
    if (km > maxKm) continue;
    hits.push({ point, km });
  }

  hits.sort((a, b) => a.km - b.km);
  return hits.slice(0, limit);
}

/**
 * Расстояние человеку: до километра — в метрах.
 *
 * «0.3 км» требует пересчёта в уме прямо за рулём, «300 м» — нет.
 * Округление метров до полусотни честнее точности гаверсинуса на таких
 * дистанциях и не притворяется, что мы знаем дорогу до метра.
 */
export function formatKm(km: number): string {
  if (km < 1) {
    const meters = Math.max(50, Math.round((km * 1000) / 50) * 50);
    return `${meters} м`;
  }
  return `${km.toFixed(1)} км`;
}
