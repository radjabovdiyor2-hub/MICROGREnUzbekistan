import { distanceKm } from './dayRoute';

// ══════════════════════════════════════════════════════════════════════
// Подтверждение места: был ли сотрудник у клиента, когда отмечал визит.
//
// ЗАЧЕМ. Отметка «был» ставилась пальцем из любой точки города, и проверить
// её было нечем. Владелец сформулировал прямо: «а не мухлёвка, что сходил,
// хотя не ходил».
//
// ПОЧЕМУ НЕ ЗАПРЕЩАЕМ, А ПОМЕЧАЕМ
//
// Соблазн — не принимать отметку, если телефон говорит «далеко». Так делать
// нельзя, и вот почему: GPS в подвале ресторана, в железном павильоне или
// при отказе в доступе к геолокации не берётся вовсе или врёт на километры.
// Запрет означал бы, что честный продавец, стоящий у дверей, не может
// отметить визит и уходит без записи, — потерянная отметка хуже
// неподтверждённой.
//
// Поэтому: место записывается, расстояние считает СЕРВЕР (клиент прислал бы
// любое), а владелец видит на карточке, чем отметка подтверждена. Это
// решает исходную задачу — видимость, — не ломая полевую работу.
//
// ЕЩЁ ОДНА ПРИЧИНА НЕ ЗАПРЕЩАТЬ: у самого клиента пин может стоять неверно.
// Продавец приехал к дверям, а пин лежит в соседнем квартале — «далеко»
// скажет о пине, а не о человеке. Ровно для этого рядом и живёт кнопка
// «Переставить пин».
// ══════════════════════════════════════════════════════════════════════

/**
 * Насколько близко считаем «был у клиента».
 *
 * 150 метров — не догадка: городской квартал в Самарканде порядка 100–200 м,
 * а пин заведения обычно стоит на здании, тогда как продавец — у входа,
 * во дворе или на парковке. Меньше — и честные визиты начнут помечаться
 * далёкими; больше — и «рядом» перестанет что-либо значить.
 */
export const NEAR_METERS = 150;

/**
 * Точность хуже этой делает вывод бессмысленным.
 *
 * Если браузер сообщает круг радиусом полкилометра, то и «40 м до клиента»,
 * и «400 м» — одно и то же число внутри погрешности. Честнее сказать
 * «место не подтверждено», чем нарисовать зелёную галочку по шуму.
 */
export const USELESS_ACCURACY_M = 500;

export type ProofKind = 'near' | 'far' | 'rough' | 'none';

export interface VisitProof {
  kind: ProofKind;
  /** Расстояние в метрах, если его удалось посчитать. */
  distanceM: number | null;
}

/** Расстояние между двумя точками в МЕТРАХ, целое. */
export function metersBetween(
  a: { latitude: number; longitude: number },
  b: { latitude: number; longitude: number },
): number {
  return Math.round(distanceKm(a, b) * 1000);
}

/**
 * Что показывать владельцу рядом с отметкой.
 *
 * Разделено на четыре исхода, а не на «да/нет»: «далеко» и «точность
 * никакая» — разные истории, и путать их значит либо обвинить невиновного,
 * либо прикрыть виноватого.
 */
export function visitProof(
  distanceM: number | null | undefined,
  accuracyM: number | null | undefined,
): VisitProof {
  if (distanceM === null || distanceM === undefined) return { kind: 'none', distanceM: null };

  if (typeof accuracyM === 'number' && accuracyM > USELESS_ACCURACY_M) {
    return { kind: 'rough', distanceM };
  }

  // Погрешность работает В ПОЛЬЗУ сотрудника: если круг неопределённости
  // дотягивается до клиента, значит человек мог там стоять, и обвинять его
  // числом нельзя.
  const effective = Math.max(0, distanceM - (accuracyM ?? 0));
  return { kind: effective <= NEAR_METERS ? 'near' : 'far', distanceM };
}

/** Человеческая подпись: «рядом · 40 м», «в 3.2 км», «место не подтверждено». */
export function proofLabel(proof: VisitProof, lang: 'ru' | 'uz'): string {
  const distance =
    proof.distanceM === null
      ? ''
      : proof.distanceM < 1000
        ? `${proof.distanceM} м`
        : `${(proof.distanceM / 1000).toFixed(1)} км`;

  if (proof.kind === 'none') {
    return lang === 'ru' ? 'место не подтверждено' : 'joy tasdiqlanmagan';
  }
  if (proof.kind === 'rough') {
    return lang === 'ru' ? `место неточно (${distance})` : `joy aniq emas (${distance})`;
  }
  if (proof.kind === 'near') {
    return lang === 'ru' ? `рядом · ${distance}` : `yaqin · ${distance}`;
  }
  return lang === 'ru' ? `далеко · ${distance}` : `uzoq · ${distance}`;
}

/** Токен цвета для подписи. Красным светим только явное «далеко». */
export function proofToken(kind: ProofKind): string {
  if (kind === 'near') return 'var(--success)';
  if (kind === 'far') return 'var(--error)';
  return 'var(--text-muted)';
}
