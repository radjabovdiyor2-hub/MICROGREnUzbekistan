// ══════════════════════════════════════════════════════════════════════
// Куда ведёт «назад» в админке.
//
// ПРОБЛЕМА
//
// Открыв админку внутри Telegram, человек жмёт аппаратное «назад» — и
// ВЫХОДИТ ИЗ ПРИЛОЖЕНИЯ, вместо того чтобы вернуться к списку. Причина в
// том, что переходы «список → карточка» вообще не попадают в историю: они
// живут в локальном состоянии экрана (`selectedId`, `selected`), а вкладки
// меняются через `replaceState` — намеренно, чтобы «назад» не отматывал по
// одной вкладке за нажатие (см. `useAdminTab`).
//
// РЕШЕНИЕ
//
// Не трогаем историю браузера, а заводим свою стопку возвратов. Экран,
// открывший карточку, кладёт сюда способ её закрыть; Telegram показывает
// свою кнопку «назад», пока в стопке что-то есть, и вызывает верхний
// обработчик. Пусто — кнопка спрятана, и «назад» снова означает «выйти»,
// что на верхнем уровне и верно.
//
// Стопка, а не одно значение: карточка клиента умеет открыть поверх себя
// кассу, и возврат должен идти по одному шагу, а не сразу на список.
//
// Модуль без React намеренно: его читает и компонент Telegram-инициализации,
// и обычные экраны, а состояние должно пережить их перемонтирование.
// ══════════════════════════════════════════════════════════════════════

type BackHandler = () => void;
type Listener = (depth: number) => void;

const stack: BackHandler[] = [];
const listeners = new Set<Listener>();

function announce(): void {
  for (const listener of listeners) listener(stack.length);
}

/**
 * Объявить, что открыт вложенный экран.
 *
 * Возвращает функцию снятия — её и надо вызывать в `useEffect`-очистке.
 * Снятие идёт по ссылке, а не «сверху»: экраны закрываются не всегда в
 * обратном порядке, и снятие верхнего наугад однажды убрало бы чужой.
 */
export function pushBack(handler: BackHandler): () => void {
  stack.push(handler);
  announce();

  return () => {
    const at = stack.lastIndexOf(handler);
    if (at === -1) return;
    stack.splice(at, 1);
    announce();
  };
}

/**
 * Выполнить возврат на один шаг. `false` — возвращаться некуда.
 *
 * Обработчик СНИМАЕТСЯ здесь же, до вызова. Полагаться на то, что экран
 * снимет себя сам очисткой эффекта, нельзя: пока он этого не сделал (а
 * React делает это не мгновенно), повторное нажатие «назад» вызвало бы тот
 * же обработчик второй раз. Двойное снятие безопасно — `pushBack` ищет
 * обработчик по ссылке и на отсутствующем ничего не делает.
 */
export function goBack(): boolean {
  const handler = stack.pop();
  if (!handler) return false;
  announce();
  handler();
  return true;
}

/** Сколько вложенных экранов открыто. 0 — мы на верхнем уровне. */
export function backDepth(): number {
  return stack.length;
}

/** Подписка на изменение глубины. Сразу сообщает текущее значение. */
export function onBackDepth(listener: Listener): () => void {
  listeners.add(listener);
  listener(stack.length);
  return () => {
    listeners.delete(listener);
  };
}
