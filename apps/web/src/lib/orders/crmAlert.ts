import { prisma } from '@repo/database';

// ══════════════════════════════════════════════════════════════════════
// Сигнал владельцу: заказ не доехал до CRM офиса.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ СТРОКА В notify.ts
//
// Отказ моста витрина → офис гасится намеренно: падение офиса не должно
// срывать покупателю заказ. Плата за это — тишина. 18.08.2026 выяснилось,
// что на проде пустой `INGEST_SECRET`, офис отвечал 401 на КАЖДЫЙ
// `/ingest/*`, и ни один заказ с сайта не попал в CRM. Сайт при этом
// выглядел совершенно здоровым: запись уходила в аудит и в счётчик, а
// владельцу — никуда. Поломка жила незамеченной, пока не попробовали
// нажать кнопку геокодирования, которая ходит в ту же дверь.
//
// Аудит отвечает на вопрос «что случилось», когда его уже задали.
// Оповещение задаёт вопрос само.
//
// ПОЧЕМУ С ГАШЕНИЕМ ПОВТОРОВ
//
// Мост ломается не для одного заказа, а для всех сразу. Без гашения
// каждый заказ породил бы своё оповещение, и вкладка сигналов
// превратилась бы в ленту одинаковых строк — то есть перестала бы
// значить что-либо.
// ══════════════════════════════════════════════════════════════════════

/** Один сигнал в час: мост чинится руками, чаще напоминать бессмысленно. */
const QUIET_MS = 60 * 60 * 1000;

const KIND = 'crm_sync_failed';

/**
 * Поднять тревогу о неработающем мосте в CRM.
 *
 * Никогда не бросает исключение: её зовут из пути, где заказ уже создан, и
 * уронить его из-за неудачной записи оповещения было бы хуже самой тишины.
 */
export async function alertCrmSyncFailed(input: {
  /** Номер заказа или чека — чтобы владелец мог показать конкретную запись. */
  target: string;
  /**
   * `order` — заказ с сайта, `pos` — продажа за прилавком или с выезда,
   * `refund` — возврат. Возврат стоит отдельно намеренно: непрошедший
   * возврат оставляет клиенту ЗАВЫШЕННУЮ сумму покупок, и владельцу важно
   * прочитать в сигнале именно это, а не «продажа не доехала».
   */
  channel: 'order' | 'pos' | 'refund';
  /** Что именно ответил офис, если это известно. */
  reason?: string;
}): Promise<void> {
  try {
    const since = new Date(Date.now() - QUIET_MS);
    const already = await prisma.ownerAlert.findFirst({
      where: { kind: KIND, createdAt: { gte: since } },
      select: { id: true },
    });
    if (already) return;

    const what =
      input.channel === 'pos'
        ? 'Продажа за прилавком'
        : input.channel === 'refund'
          ? 'Возврат за прилавком'
          : 'Заказ с сайта';

    await prisma.ownerAlert.create({
      data: {
        kind: KIND,
        severity: 'critical',
        title: 'Заказы не доходят до CRM офиса',
        message:
          `${what} ${input.target} не попал в CRM: офис не принял запрос` +
          (input.reason ? ` (${input.reason})` : '') +
          '. Пока мост лежит, ни Стёпан, ни финансы, ни аналитика заказов не ' +
          'видят, а карточки клиентов и статусы не синхронизируются. Частая ' +
          'причина — пустой INGEST_SECRET: он задаётся в GitHub Secrets и ' +
          'попадает на сервер при выкатке. Проверить: docker logs mg_web_office.',
        source: 'web',
      },
    });
  } catch (err) {
    // Оповещение не имеет права уронить оформление заказа — тот же контракт,
    // что у аудита. Но в лог это обязано попасть.
    console.error('[crm] не удалось записать оповещение о падении моста:', err);
  }
}
