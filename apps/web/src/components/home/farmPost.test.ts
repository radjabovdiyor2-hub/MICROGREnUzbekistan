import { describe, expect, it } from 'vitest';

import { isFarmPost } from './FarmSection';

// ══════════════════════════════════════════════════════════════════════
// СЛУЧАЙ, РАДИ КОТОРОГО НАПИСАН ЭТОТ ТЕСТ.
//
// Блок «Как мы выращиваем» брал четыре свежих кадра ленты Instagram. На
// бою под этим заголовком и подписью «теплица, срезка и упаковка»
// оказались: фотография встречи с представителем ООН и два рекламных
// плаката про салаты.
//
// Заметить это на стенде было невозможно. Токена там нет, лента отвечает
// пустым списком, блок гаснет — и выглядит совершенно исправным. Ни один
// тест, линтер или сборка не видят разницы между «показывает процесс» и
// «показывает что попало»: и то и другое — четыре картинки в сетке.
//
// Теперь пост попадает в блок только с меткой. Правило простое, и именно
// поэтому его легко однажды ослабить до «содержит слово ферма» — а тогда
// сюда вернётся реклама с текстом про нашу ферму.
// ══════════════════════════════════════════════════════════════════════

describe('isFarmPost', () => {
  it('пост с меткой — кадр с производства', () => {
    expect(isFarmPost('Утренняя срезка #ferma')).toBe(true);
    expect(isFarmPost('Упаковка #ферма #organic')).toBe(true);
  });

  it('метка узнаётся в любом регистре', () => {
    // Человек ставит её с телефона между делом и не обязан помнить
    // единственно верное написание.
    expect(isFarmPost('#Ferma утро')).toBe(true);
    expect(isFarmPost('#ТЕПЛИЦА')).toBe(true);
  });

  it('несколько написаний метки принимаются', () => {
    expect(isFarmPost('#jarayon')).toBe(true);
    expect(isFarmPost('#процесс')).toBe(true);
    expect(isFarmPost('#teplitsa')).toBe(true);
  });

  it('РЕАЛЬНЫЕ посты, которые попали в блок ошибочно, теперь не проходят', () => {
    // Дословно то, что висело на бою под заголовком «Как мы выращиваем».
    expect(
      isFarmPost('Today in Samarkand — a meeting with Felipe Paullier, UN Assistant Secretary-General'),
    ).toBe(false);
    expect(isFarmPost('После ужина хочется не тяжести, а лёгкости')).toBe(false);
    expect(isFarmPost('🍽 Salat va Mikrozelenlar: Yozgi Taomlar Ustida Yozish 🌱')).toBe(false);
  });

  it('слово без решётки меткой не считается', () => {
    // Иначе в блок вернётся реклама, где просто написано «наша ферма».
    expect(isFarmPost('Наша ферма работает с 2023 года — заказывайте!')).toBe(false);
    expect(isFarmPost('процесс выращивания занимает неделю')).toBe(false);
  });

  it('пустая подпись — не кадр с производства', () => {
    expect(isFarmPost(undefined)).toBe(false);
    expect(isFarmPost('')).toBe(false);
  });

  it('обычные метки магазина блок не наполняют', () => {
    // `#микрозелень` и `#organic` стоят почти на каждом посте ленты — по
    // ним в блок снова попало бы всё подряд.
    expect(isFarmPost('Салаты Romano, Frize #микрозелень #organic #restaurant')).toBe(false);
  });
});
