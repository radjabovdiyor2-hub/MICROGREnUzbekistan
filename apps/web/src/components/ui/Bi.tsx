'use client';

import { useLang } from '@/components/providers/LangProvider';

// ══════════════════════════════════════════════════════════════════════
// Строка на языке читателя внутри СЕРВЕРНОЙ страницы.
//
// ЗАЧЕМ. По сайту нашёлся один и тот же дефект в трёх местах: текст лежит
// двуязычным — и в коде страницы, и в базе, — а показывается всегда
// русский. Узбекский читатель видел чужой язык там, где перевод давно
// написан и просто не выводился.
//
// Причина у всех одна: страницы серверные (иначе разметку для поиска
// считает не краулер, а браузер), а язык читателя живёт в браузере. Делать
// клиентской ВСЮ страницу ради двух абзацев — плата не по счёту.
//
// Поэтому клиентским становится только само слово. Серверная страница
// по-прежнему отдаёт полную разметку; в первой отрисовке стоит русский
// вариант, и через мгновение он заменяется узбекским у тех, у кого выбран
// узбекский.
//
// НЕТ ПЕРЕВОДА — ПОКАЗЫВАЕМ РУССКИЙ. Пустота вместо абзаца хуже чужого
// языка: человек решит, что страница сломана.
// ══════════════════════════════════════════════════════════════════════

export function Bi({ ru, uz }: { ru: string; uz?: string | null }) {
  const { lang } = useLang();
  return <>{lang === 'uz' ? (uz || ru) : ru}</>;
}
