import { describe, expect, it } from 'vitest';

import { isAllSelected, withAllToggled, withOnlyVisible } from './useSelection';

// ══════════════════════════════════════════════════════════════════════
// Выбор нескольких записей.
//
// Проверяется не «работает ли переключатель» — это видно глазами, — а три
// тонкости, которые ломаются МОЛЧА и стоят удалённых не тех записей:
//
//   1. «Выбрать всё» ДОПОЛНЯЕТ, а не заменяет: выбранное на предыдущей
//      странице не должно исчезать от нажатия на этой.
//   2. Повторное «выбрать всё» снимает ТОЛЬКО видимое, оставляя чужое.
//   3. `withOnlyVisible` выкидывает то, что ушло из-под фильтра. Без него
//      «Удалить выбранные» уносит записи, которых нет на экране.
//
// Проверяются чистые функции, а не хук: решения живут в них, и такой тест
// не требует ни рендера компонента, ни новой зависимости в проекте.
// ══════════════════════════════════════════════════════════════════════

describe('выбрать всё видимое', () => {
  it('дополняет выбор, а не заменяет его', () => {
    // 99 выбрано на «прошлой странице», [1,2] — то, что видно сейчас.
    expect(withAllToggled([99], [1, 2])).toEqual([99, 1, 2]);
  });

  it('повторное нажатие снимает только видимое', () => {
    const afterAll = withAllToggled([99], [1, 2]);
    // Человек снимал выбор с того, что перед ним. Чужое остаётся.
    expect(withAllToggled(afterAll, [1, 2])).toEqual([99]);
  });

  it('не удваивает уже выбранное', () => {
    expect(withAllToggled([1], [1, 2])).toEqual([1, 2]);
  });

  it('пустой список видимого ничего не меняет', () => {
    expect(withAllToggled([1, 2], [])).toEqual([1, 2]);
  });

  it('работает со строковыми ключами — у заказов это cuid', () => {
    expect(withAllToggled([], ['a', 'b'])).toEqual(['a', 'b']);
  });
});

describe('признак «выбрано всё»', () => {
  it('считается по видимому, а не по всей базе', () => {
    expect(isAllSelected([1, 2], [1, 2])).toBe(true);
    // Появилась третья запись — выбор уже не полный.
    expect(isAllSelected([1, 2], [1, 2, 3])).toBe(false);
  });

  it('пустой экран не считается выбранным целиком', () => {
    // Иначе галка «выбрать всё» стояла бы на пустом списке.
    expect(isAllSelected([], [])).toBe(false);
    expect(isAllSelected([1], [])).toBe(false);
  });
});

describe('смена фильтра', () => {
  it('выкидывает из выбора то, что пропало с экрана', () => {
    expect(withOnlyVisible([1, 2, 3], [2])).toEqual([2]);
  });

  it('сохраняет ССЫЛКУ, когда ничего не пропало', () => {
    const before = [1, 2];
    // Та же ссылка: иначе каждый прогон опроса списка вызывал бы лишнюю
    // перерисовку всего экрана.
    expect(withOnlyVisible(before, [1, 2, 3])).toBe(before);
  });

  it('пустой видимый список очищает выбор', () => {
    expect(withOnlyVisible([1, 2], [])).toEqual([]);
  });
});
