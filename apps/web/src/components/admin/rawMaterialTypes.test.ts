import { describe, expect, it } from 'vitest';

import { materialName } from './rawMaterialTypes';

// ══════════════════════════════════════════════════════════════════════
// Имя позиции сырья на двух языках.
//
// Проверяется ровно одно решение: НЕЗАПОЛНЕННОЕ узбекское имя не должно
// превращаться в пустую строку. Колонка добавлена пустой на все 32
// позиции, и владелец заполняет её постепенно — всё это время экран обязан
// показывать русское название, а не пропадающие строки.
// ══════════════════════════════════════════════════════════════════════

describe('materialName', () => {
  it('узбекское имя показывается, когда оно заполнено', () => {
    expect(materialName({ name: 'Кокосовый субстрат', nameUz: 'Kokos substrati' }, 'uz'))
      .toBe('Kokos substrati');
  });

  it('пустое узбекское имя откатывается к русскому, а не к пустоте', () => {
    // ПОДСАДКА, ПОКАЗАННАЯ КРАСНОЙ: верни сюда `m.nameUz ?? ''` — и обе
    // проверки ниже краснеют, а на экране 32 позиции станут пустыми строками.
    expect(materialName({ name: 'Кокосовый субстрат', nameUz: null }, 'uz'))
      .toBe('Кокосовый субстрат');
    expect(materialName({ name: 'Кокосовый субстрат', nameUz: '   ' }, 'uz'))
      .toBe('Кокосовый субстрат');
  });

  it('русскому читателю узбекское имя не подставляется никогда', () => {
    expect(materialName({ name: 'Лоток 10×20', nameUz: 'Lotok 10×20' }, 'ru'))
      .toBe('Лоток 10×20');
  });
});
