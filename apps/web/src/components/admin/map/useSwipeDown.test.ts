import { describe, expect, it } from 'vitest';

import { isSwipeDown } from './useSwipeDown';

// ══════════════════════════════════════════════════════════════════════
// Смахнуть вниз — закрыть.
//
// Проверяются пороги, а не наличие обработчика: именно они ломаются молча
// и в обе стороны сразу.
//
//   • ослабишь — лист закрывается сам, когда человек листает ленту
//     фильтров вбок, и выглядит это как «панель исчезает произвольно»;
//   • ужесточишь — жест перестаёт срабатывать, и владелец снова скажет
//     «свайпов нет», хотя код на месте.
//
// Ни то ни другое не видно ни в типах, ни в линтере.
// ══════════════════════════════════════════════════════════════════════

const at = (x: number, y: number, t: number) => ({ x, y, t });

describe('смахивание вниз', () => {
  it('уверенное движение вниз закрывает', () => {
    expect(isSwipeDown(at(100, 100, 0), at(100, 200, 200))).toBe(true);
  });

  it('короткое движение не считается — палец дрогнул', () => {
    // 40 пикселей меньше порога 56: столько проходит палец, просто нажимая.
    expect(isSwipeDown(at(100, 100, 0), at(100, 140, 120))).toBe(false);
  });

  it('движение ВВЕРХ не закрывает', () => {
    expect(isSwipeDown(at(100, 200, 0), at(100, 100, 150))).toBe(false);
  });

  it('листание вбок с уклоном вниз не закрывает', () => {
    // 80 вниз, 120 вбок — это лента фильтров, а не закрытие.
    expect(isSwipeDown(at(100, 100, 0), at(220, 180, 200))).toBe(false);
  });

  it('диагональ с явным перевесом вниз закрывает', () => {
    // 120 вниз при 40 вбок — перевес втрое, порог 1.6 пройден.
    expect(isSwipeDown(at(100, 100, 0), at(140, 220, 250))).toBe(true);
  });

  it('медленное ведение пальцем не закрывает', () => {
    // Расстояние набрано, но за две секунды — это не смахивание.
    expect(isSwipeDown(at(100, 100, 0), at(100, 300, 2000))).toBe(false);
  });

  it('пороги настраиваются — лист и полоса могут просить разного', () => {
    const from = at(100, 100, 0);
    const to = at(100, 145, 150);
    expect(isSwipeDown(from, to)).toBe(false);
    expect(isSwipeDown(from, to, { distance: 40 })).toBe(true);
  });
});
