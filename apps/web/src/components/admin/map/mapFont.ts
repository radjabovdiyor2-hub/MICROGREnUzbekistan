// Шрифт подписей на карте.
//
// Symbol-слой без `text-font` получает от MapLibre её умолчательный стек
// `Open Sans Regular, Arial Unicode MS Regular`, которого наш хост тайлов
// не отдаёт. Проверено запросами к нему:
//
//   /fonts/Open Sans Regular,Arial Unicode MS Regular/0-255.pbf     → 404
//   /fonts/Open Sans Regular,Arial Unicode MS Regular/1024-1279.pbf → 404
//   /fonts/Noto Sans Regular/0-255.pbf                              → 200
//   /fonts/Noto Sans Regular/1024-1279.pbf                          → 200  (кириллица)
//
// Стиль объявляет `glyphs: …/fonts/{fontstack}/{range}.pbf` и везёт ровно
// Noto Sans (Regular | Bold | Italic).
//
// ЧТО ПРИ ЭТОМ НЕ ЛОМАЕТСЯ, вопреки первому впечатлению: подписи всё
// равно рисуются. MapLibre 6 на провалившийся глиф молча откатывается на
// системный шрифт клиента — событие `error` при этом НЕ выбрасывается.
// Проверено в браузере: кириллица и латиница в одной строке выглядят
// одинаково с явным стеком и без него.
//
// Поэтому явный `text-font` — это не починка пропавших подписей, а две
// вещи поменьше:
//
//   1. Гарантированный 404 на каждый затронутый диапазон Unicode при
//      каждой загрузке карты. Запрос заведомо обречён, и мы его делаем.
//   2. Типографика перестаёт зависеть от устройства. Откат берёт то, что
//      найдётся в системе: на Windows одно, на Android другое, на старом
//      телефоне с бедным набором кириллицы — третье. Noto Sans приезжает
//      с тайлами и одинаков везде.
//
// Отсюда правило: КАЖДЫЙ symbol-слой задаёт `text-font` явно. Тест в
// mapLayers.test.ts следит, чтобы новый слой не завели снова без него.
//
// Диапазон 1024–1279 — это U+0400…U+04FF: имена клиентов записаны и
// кириллицей, и латиницей вперемешку, и обе половины обязаны рисоваться.
// ══════════════════════════════════════════════════════════════════════

/** Единственный стек, который отдаёт наш хост тайлов. */
export const MAP_FONT = ['Noto Sans Regular'];

/** Тот же стек пожирнее — для подписей, которым нужен вес. */
export const MAP_FONT_BOLD = ['Noto Sans Bold'];
