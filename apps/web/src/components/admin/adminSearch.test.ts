import { describe, expect, it } from 'vitest';

import { matchesQuery } from './AdminSearch';

// ══════════════════════════════════════════════════════════════════════
// Сравнение записи с запросом — на нём стоит поиск на девяти экранах.
//
// Ошибка здесь не падает, а тихо прячет записи: человек ищет «плов центр»,
// не находит и заводит второго клиента с тем же названием. Поэтому
// проверяется не только «находит», но и «показывает всё, когда не ищут».
// ══════════════════════════════════════════════════════════════════════

describe('поиск по списку', () => {
  it('пустой запрос показывает всё', () => {
    // Экран без ввода обязан показывать полный список, а не пустоту.
    expect(matchesQuery('', 'Плов Центр')).toBe(true);
    expect(matchesQuery('   ', 'Плов Центр')).toBe(true);
  });

  it('не различает регистр и лишние пробелы', () => {
    expect(matchesQuery('плов центр', 'Плов Центр')).toBe(true);
    expect(matchesQuery('  ПЛОВ  ', 'Плов Центр')).toBe(true);
  });

  it('ищет по любому из полей', () => {
    expect(matchesQuery('9989', 'Плов Центр', '+998901112233')).toBe(true);
    expect(matchesQuery('регистан', 'Плов Центр', null, 'ул. Регистан')).toBe(true);
  });

  it('пропускает пустые поля, а не падает на них', () => {
    // У половины карточек телефон и заметка пустые.
    expect(matchesQuery('плов', null, undefined, 'Плов')).toBe(true);
    expect(matchesQuery('плов', null, undefined)).toBe(false);
  });

  it('числа сравниваются как текст', () => {
    // Суммы и id — числа, а человек ищет их строкой.
    expect(matchesQuery('120', 'Долг', 120000)).toBe(true);
  });

  it('не находит того, чего нет', () => {
    expect(matchesQuery('шашлык', 'Плов Центр', '+998901112233')).toBe(false);
  });
});
