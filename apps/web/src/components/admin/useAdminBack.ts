'use client';

import { useEffect } from 'react';

import { pushBack } from '@/lib/adminBack';

// ══════════════════════════════════════════════════════════════════════
// «Назад» из вложенного экрана — один хук на все карточки.
//
// Открыв карточку заказа внутри Telegram, человек жмёт аппаратное «назад»
// и ВЫХОДИТ ИЗ ПРИЛОЖЕНИЯ: переход «список → карточка» живёт в состоянии
// экрана и в историю браузера не попадает. Экран, вызвавший этот хук,
// перехватывает кнопку на время своей жизни.
//
// Снимается автоматически при размонтировании — то есть ровно тогда, когда
// карточка закрылась любым другим способом.
// ══════════════════════════════════════════════════════════════════════

/**
 * Перехватить «назад», пока экран открыт.
 *
 * @param onBack как закрыть экран. Должен быть стабильным между рендерами
 *               либо честно попадать в зависимости — иначе перехват будет
 *               сниматься и ставиться заново на каждый рендер.
 * @param active `false` — не перехватывать (экран ещё не открыт)
 */
export function useAdminBack(onBack: () => void, active: boolean = true): void {
  useEffect(() => {
    if (!active) return;
    return pushBack(onBack);
  }, [onBack, active]);
}
