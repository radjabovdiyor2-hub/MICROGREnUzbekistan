// ══════════════════════════════════════════════════════════════════════
// Что отдаёт дверь «кто сейчас в поле».
//
// Отдельным файлом, потому что читателей у этой формы трое: общий список,
// экран слежения за одним человеком и строка человека. Три копии формы
// разошлись бы на первой же правке двери.
// ══════════════════════════════════════════════════════════════════════

export interface LivePoint {
  at: string;
  latitude: number;
  longitude: number;
  accuracyM: number | null;
}

export interface LivePerson {
  id: string;
  name: string;
  startedAt: string;
  meters: number;
  stops: number;
  /** Путь за день. Может быть обрезан — см. `trimmed`. */
  track: LivePoint[];
  /** Самая свежая точка. `null` — сегодня не прислал ни одной. */
  last: LivePoint | null;
  /** Крошек всего за день, а не в показанном куске: по ним считается частота. */
  points: number;
  /** Чем снята последняя крошка: `app`, `pwa`, `telegram_live`. */
  lastSource: string | null;
  /** Показан только последний отрезок пути: день целиком не поместился. */
  trimmed: boolean;
  /**
   * Молчит столько минут — НА МОМЕНТ ОТВЕТА СЕРВЕРА.
   *
   * Пока ответ лежит в кэше, число устаревает; стареть его обязан
   * показывающий (`agedSilentMin`). `null` — не прислал ни одной точки,
   * и это не то же самое, что «молчит ноль минут».
   */
  silentMin: number | null;
}

export interface LiveAnswer {
  people: LivePerson[];
  /** Момент ответа сервера. От него и считается возраст молчания. */
  at: number;
}
