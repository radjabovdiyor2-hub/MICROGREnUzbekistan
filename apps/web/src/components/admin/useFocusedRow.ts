'use client';

import { useCallback, useEffect, useRef, type CSSProperties } from 'react';

// ══════════════════════════════════════════════════════════════════════
// «Вот та самая запись, ради которой вы пришли».
//
// ЗАЧЕМ
//
// Офис строит ссылки вида `/admin?tab=orders&focus=<order_id>` — их выдают
// карточки подтверждения, дайджест заявок и кнопки под докладами. Вкладку
// адрес открывает исправно, а вот ПОДСВЕЧИВАТЬ запись умели ровно два
// экрана из пятидесяти: заказы и задачи. На остальных человек приходил по
// ссылке про запись #57 и дальше искал её глазами в списке — то есть
// ссылка экономила один шаг из двух.
//
// Хуже того, расхождение невидимо: ссылка открывается, ошибок нет, просто
// «не пригодилось». Сверка `check_tools.py` проверяет, что вкладка
// существует, но не что она умеет показать запись.
//
// ЧТО ЗДЕСЬ
//
// Тот же приём, что уже был у задач (`AdminTaskRow`): обводка цветом бренда
// и доскролл до строки. Вынесен, чтобы одиннадцать экранов не изобретали
// его заново и не разошлись в оформлении.
// ══════════════════════════════════════════════════════════════════════

/** Совпадает ли запись с тем, что просили в адресе. */
export function isFocused(focus: string, ...ids: (string | number | null | undefined)[]): boolean {
  if (!focus) return false;
  return ids.some((id) => id !== null && id !== undefined && String(id) === focus);
}

/**
 * Оформление подсвеченной строки.
 *
 * Обводка, а не заливка: заливка спорила бы с цветными плашками статусов,
 * которые на этих же карточках и живут.
 */
export function focusOutline(focused: boolean): CSSProperties {
  return focused ? { outline: '2px solid var(--brand-primary)', outlineOffset: 2 } : {};
}

/**
 * Ссылка на элемент, к которому надо прокрутить экран.
 *
 * Прокрутка один раз на появление признака: повторный доскролл при каждом
 * обновлении списка дёргал бы экран под руками у человека.
 */
export function useScrollIntoView<T extends HTMLElement>(focused: boolean) {
  const ref = useRef<T>(null);

  useEffect(() => {
    if (focused) ref.current?.scrollIntoView({ block: 'center', behavior: 'smooth' });
  }, [focused]);

  return ref;
}

/**
 * То же самое для строки ВНУТРИ списка.
 *
 * Хук на каждую строку поставить нельзя — их число меняется, а правила
 * хуков этого не прощают. Поэтому обратный вызов: вешается только на
 * подсвеченную строку и срабатывает в момент её появления в разметке.
 *
 * `once` защищает от повторного доскролла: список обновляется опросом, и
 * без него экран дёргался бы под руками каждые несколько секунд.
 */
export function useScrollToFocused<T extends HTMLElement>() {
  const done = useRef(false);

  return useCallback((node: T | null) => {
    if (!node || done.current) return;
    done.current = true;
    node.scrollIntoView({ block: 'center', behavior: 'smooth' });
  }, []);
}
