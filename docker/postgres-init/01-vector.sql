-- ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Образ pgvector/pgvector только ПРИВОЗИТ
-- расширение, но не включает его: в новой базе типа `vector` нет, пока
-- кто-нибудь не выполнит CREATE EXTENSION. В схеме же есть колонка
-- Unsupported("vector(1536)") — база знаний поддержки, — и `prisma db push`
-- на такой базе падает первой же таблицей:
--
--     Error: ERROR: type "vector" does not exist
--
-- То есть поднять локальный стенд по README было всё ещё нельзя. Смена
-- образа полдела не доделала: она убрала «нет такого расширения», но
-- оставила «расширение есть и выключено».
--
-- КАК ЭТО РАБОТАЕТ. Всё из /docker-entrypoint-initdb.d выполняется ОДИН
-- РАЗ — при создании тома. На уже созданном томе файл не запускается, и
-- это не беда: там расширение либо включено, либо включается руками той
-- же строкой.
-- ══════════════════════════════════════════════════════════════════════
CREATE EXTENSION IF NOT EXISTS vector;
